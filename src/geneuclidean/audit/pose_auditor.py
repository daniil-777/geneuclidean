@dataclass(frozen=True)
class PoseAuditReport:
    """Structured 7-axis physical & medicinal-chemistry audit report for a 3D complex."""

    name: str
    smiles: str
    # Axis 1: PoseBusters-equivalent geometry
    passed_posebusters: bool
    posebusters_details: dict[str, Any]
    # Axis 2: Saturated-ring conformational strain
    passed_ring_strain: bool
    ring_strain: dict[str, Any]
    # Axis 3: Rotatable-bond torsion strain
    passed_torsion_strain: bool
    torsion_strain: dict[str, Any]
    # Axis 4: pH 7.4 tautomer & microstate electrostatics
    passed_microstate: bool
    microstate: dict[str, Any]
    # Axis 5: 6-channel 3D PLIF & canonical anchor engagement
    passed_interactions: bool
    interactions_summary: dict[str, Any]
    # Axis 6: MedChem hygiene & reagent quarantine
    passed_hygiene: bool
    hygiene_gate: float
    hygiene_alerts: tuple[str, ...]
    # Axis 7: Therapeutic profile & optional Avoid-ome
    property_profile: dict[str, Any]
    admet_summary: dict[str, Any] | None
    # Aggregate verdicts
    passed_physical_beyond_pb: bool
    passed_all_7_axes: bool
    reality_score: float
    failure_reasons: tuple[str, ...] = ()

    def to_dict(self) -> dict[str, Any]:
        return {
            "name": self.name,
            "smiles": self.smiles,
            "passed_posebusters": self.passed_posebusters,
            "passed_ring_strain": self.passed_ring_strain,
            "passed_torsion_strain": self.passed_torsion_strain,
            "passed_microstate": self.passed_microstate,
            "passed_interactions": self.passed_interactions,
            "passed_hygiene": self.passed_hygiene,
            "passed_physical_beyond_pb": self.passed_physical_beyond_pb,
            "passed_all_7_axes": self.passed_all_7_axes,
            "reality_score": round(self.reality_score, 4),
            "failure_reasons": list(self.failure_reasons),
            "posebusters": self.posebusters_details,
            "ring_strain": self.ring_strain,
            "torsion_strain": self.torsion_strain,
            "microstate": self.microstate,
            "interactions": self.interactions_summary,
            "hygiene_gate": round(self.hygiene_gate, 4),
            "hygiene_alerts": list(self.hygiene_alerts),
            "property_profile": self.property_profile,
            "admet": self.admet_summary,
        }

    def to_markdown(self) -> str:
        """Render a concise, human-readable Markdown audit card."""

        def _badge(ok: bool) -> str:
            return "PASS" if ok else "FAIL"

        lines = [
            f"### Pose Reality Audit — `{self.name}` (`reality_score = {self.reality_score:.3f}`)",
            f"- **SMILES:** `{self.smiles}`",
            f"- **Verdict:** PoseBusters=`{_badge(self.passed_posebusters)}` | "
            f"Beyond-PoseBusters Physical=`{_badge(self.passed_physical_beyond_pb)}` | "
            f"All 7 Axes=`{_badge(self.passed_all_7_axes)}`",
            "",
            "| Axis | Status | Key Metric |",
            "| :--- | :---: | :--- |",
            f"| 1. Local Geometry & Clashes (PoseBusters) | {_badge(self.passed_posebusters)} | "
            f"protein_clashes={self.posebusters_details.get('protein_clash_count', 0)}, "
            f"intra_clashes={self.posebusters_details.get('internal_clash_count', 0)} |",
            f"| 2. Saturated-Ring Strain (Cremer-Pople) | {_badge(self.passed_ring_strain)} | "
            f"max={self.ring_strain.get('max_ring_strain_kcal', 0.0):.2f} kcal/mol "
            f"({self.ring_strain.get('n_saturated_ring_systems', 0)} systems) |",
            f"| 3. Rotatable-Bond Torsion Strain | {_badge(self.passed_torsion_strain)} | "
            f"red={self.torsion_strain.get('n_red', 0)}, "
            f"max_barrier={self.torsion_strain.get('max_local_barrier_kcal', 0.0):.2f} kcal/mol |",
            f"| 4. pH 7.4 Tautomer & Microstate | {_badge(self.passed_microstate)} | "
            f"q_in={self.microstate.get('input_formal_charge'):+d} vs "
            f"q_7.4={self.microstate.get('expected_ph74_charge'):+d}, "
            f"taut_gap={self.microstate.get('tautomer_stability_gap', 0.0):.2f} |",
            f"| 5. 6-Ch 3D PLIF & Anchors | {_badge(self.passed_interactions)} | "
            f"total_contacts={self.interactions_summary.get('total_interactions', 0)} |",
            f"| 6. MedChem Hygiene & Quarantine | {_badge(self.passed_hygiene)} | "
            f"gate={self.hygiene_gate:.2f}, alerts={len(self.hygiene_alerts)} |",
            f"| 7. Profile (`{self.property_profile.get('profile_name')}`) | "
            f"{_badge(bool(self.property_profile.get('passed')))} | "
            f"score={self.property_profile.get('score', 0.0):.3f} |",
        ]
        if self.failure_reasons:
            lines.append("")
            lines.append("**Flagged Issues:** " + "; ".join(self.failure_reasons))
        return "\n".join(lines)


def _coerce_3d_mol(pose: Chem.Mol | str | Path) -> Chem.Mol:
    """Parse an RDKit 3D Mol, SDF molblock string, or SDF file path."""
    mol: Chem.Mol | None = None
    if isinstance(pose, Chem.Mol):
        mol = pose
    elif isinstance(pose, Path):
        suppl = Chem.SDMolSupplier(str(pose), sanitize=True, removeHs=False)
        mol = suppl[0] if len(suppl) > 0 else None
    elif isinstance(pose, str):
        if "\n" in pose or "V2000" in pose or "V3000" in pose:
            mol = Chem.MolFromMolBlock(pose, sanitize=True, removeHs=False)
        else:
            suppl = Chem.SDMolSupplier(pose, sanitize=True, removeHs=False)
            mol = suppl[0] if len(suppl) > 0 else None
    if mol is None or mol.GetNumConformers() == 0:
        raise ValueError(
            "PoseRealityAuditor requires a valid 3D ligand with at least one conformer."
        )
    return mol


class PoseRealityAuditor:
    """Reusable, zero-PyTorch-core 7-axis 3D pose & lead reality auditor."""

    def __init__(
        self,
        *,
        ring_strain_threshold_kcal: float = 3.0,
        ring_n_ref_confs: int = 24,
        torsion_barrier_threshold_kcal: float = 2.5,
        torsion_max_red: int = 0,
        strict_input_charge: bool = False,
        property_profile: str = "oral_ro5",
        admet_suite: CNSAdmetSuite | None = None,
        ring_backend: str = "mmff94s",
        torsion_backend: str = "smarts_mmff94s",
        seed: int = 42,
    ) -> None:
        self.ring_strain_threshold_kcal = float(ring_strain_threshold_kcal)
        self.ring_n_ref_confs = int(ring_n_ref_confs)
        self.torsion_barrier_threshold_kcal = float(torsion_barrier_threshold_kcal)
        self.torsion_max_red = int(torsion_max_red)
        self.strict_input_charge = bool(strict_input_charge)
        self.property_profile = str(property_profile)
        self.admet_suite = admet_suite
        self.ring_backend = str(ring_backend)
        self.torsion_backend = str(torsion_backend)
        self.seed = int(seed)

    def audit(
        self,
        pose: Chem.Mol | str | Path,
        *,
        pocket_pdb: str | Path | None = None,
        name: str = "pose",
        canonical_anchors: Sequence[str] = (),
        require_any_interaction: bool = False,
    ) -> PoseAuditReport:
        """Run all 7 audit axes on one 3D ligand pose (with optional 3D binding pocket)."""
        mol_3d = _coerce_3d_mol(pose)
        mol_noh = Chem.RemoveHs(Chem.Mol(mol_3d))
        can_smi = Chem.MolToSmiles(mol_noh, canonical=True, isomericSmiles=True)

        # Resolve pocket PDB text vs path cleanly for geometry3d + interactions3d
        tmp_pdb_path: Path | None = None
        pdb_is_text = isinstance(pocket_pdb, str) and ("\n" in pocket_pdb or "ATOM  " in pocket_pdb)
        pocket_path_for_geom: Path | None = None
        if pocket_pdb is not None:
            if pdb_is_text:
                with tempfile.NamedTemporaryFile(
                    "w", suffix=".pdb", delete=False, encoding="utf-8"
                ) as tf:
                    tf.write(str(pocket_pdb))
                    tmp_pdb_path = Path(tf.name)
                pocket_path_for_geom = tmp_pdb_path
            else:
                pocket_path_for_geom = Path(pocket_pdb)

        try:
            # Axis 1: PoseBusters-equivalent local geometry & clashes
            pb = check_pose_geometry(mol_3d, pocket_pdb_path=pocket_path_for_geom)
            pb_dict = pb.to_dict()
            passed_pb = bool(pb.passed_all)

            # Axis 2: Saturated-ring conformational strain
            ring_prof: RingStrainProfile = analyze_ring_strain(
                mol_3d,
                backend=self.ring_backend,
                strain_threshold_kcal=self.ring_strain_threshold_kcal,
                n_ref_confs=self.ring_n_ref_confs,
                include_full_ligand_strain=True,
                seed=self.seed,
            )

            # Axis 3: Rotatable-bond torsion strain
            tors_prof: TorsionStrainProfile = analyze_torsion_strain(
                mol_3d,
                backend=self.torsion_backend,
                barrier_threshold_kcal=self.torsion_barrier_threshold_kcal,
                max_red_allowed=self.torsion_max_red,
                compute_local_barriers=True,
            )

            # Axis 4: pH 7.4 tautomer & microstate electrostatics
            micro: TautomerMicrostateAudit = audit_tautomer_microstate_ph74(
                mol_3d,
                pocket_pdb=pocket_pdb,
                strict_input_charge=self.strict_input_charge,
            )

            # Axis 5: 6-channel 3D PLIF & canonical anchors
            inter_summary: dict[str, Any] = {
                "profiled": False,
                "total_interactions": 0,
                "counts_by_type": {},
                "key_residues": [],
                "canonical_anchors_requested": list(canonical_anchors),
                "canonical_anchor_engaged": None,
            }
            passed_inter = True
            if pocket_pdb is not None:
                prof: InteractionProfile = (
                    profile_3d_interactions_from_pdb_text(str(pocket_pdb), mol_3d)
                    if pdb_is_text
                    else profile_3d_interactions(Path(pocket_pdb), mol_3d)
                )
                n_tot = len(prof.interactions)
                anchor_ok: bool | None = None
                if canonical_anchors:
                    req = {a.upper() for a in canonical_anchors}
                    engaged_res = {
                        r.protein_residue.upper()
                        for r in prof.interactions
                        if r.kind in ("salt_bridge", "hbond")
                    }
                    # Match exact residue token (e.g., "ASP103") or suffix ("A:ASP103")
                    anchor_ok = any(any(req_a in res_s for res_s in engaged_res) for req_a in req)
                    if not anchor_ok:
                        passed_inter = False
                if require_any_interaction and n_tot == 0:
                    passed_inter = False
                inter_summary = {
                    "profiled": True,
                    "total_interactions": n_tot,
                    "counts_by_type": dict(prof.counts_by_type),
                    "key_residues": list(prof.key_residues[:12]),
                    "canonical_anchors_requested": list(canonical_anchors),
                    "canonical_anchor_engaged": anchor_ok,
                }
        finally:
            if tmp_pdb_path is not None and tmp_pdb_path.exists():
                tmp_pdb_path.unlink(missing_ok=True)

        # Neutral parent copy for Axis 6 (triage) & Axis 7 (MPO/ADMET) so physiological
        # [NH+]/[O-] protonated docking poses do not trigger spurious charged-atom BRENK alerts.
        from rdkit.Chem.MolStandardize import rdMolStandardize

        mol_neutral = rdMolStandardize.Uncharger().uncharge(Chem.Mol(mol_noh))
        neutral_smi = Chem.MolToSmiles(mol_neutral, canonical=True, isomericSmiles=True)

        # Axis 6: Industrial MedChem hygiene & reagent quarantine
        triage = triage_molecule(mol_neutral)
        passed_hygiene = bool(triage.triage_pass)
        all_triage_alerts: tuple[str, ...] = tuple(
            dict.fromkeys(
                [
                    *triage.pains_alerts,
                    *triage.brenk_alerts,
                    *triage.nih_alerts,
                    *triage.reagent_alerts,
                    *triage.lilly_demerit_reasons,
                ]
            )
        )

        # Axis 7: Indication property profile + optional Avoid-ome
        prop_res: PropertyProfileResult = evaluate_property_profile(
            mol_neutral, profile=self.property_profile
        )
        admet_dict: dict[str, Any] | None = None
        admet_ok = True
        if self.admet_suite is not None:
            if (
                hasattr(self.admet_suite, "predict_v4")
                and len(getattr(self.admet_suite, "fitted_endpoints", ())) > 3
            ):
                vp = self.admet_suite.predict_v4([neutral_smi])[0]
                admet_dict = {
                    "profile": "v4_12ep_avoidome",
                    "admet_v4_pass": bool(vp.admet_v4_pass),
                    "probabilities": {k: round(float(v), 4) for k, v in vp.probabilities.items()},
                }
                admet_ok = bool(vp.admet_v4_pass)
            else:
                v3 = self.admet_suite.predict([neutral_smi])[0]
                admet_dict = {
                    "profile": "v3_cns",
                    "admet_pass": bool(v3.admet_pass),
                    "bbb_prob": round(float(v3.bbb_prob), 4),
                    "pgp_prob": round(float(v3.pgp_prob), 4),
                    "herg_prob": round(float(v3.herg_prob), 4),
                }
                admet_ok = bool(v3.admet_pass)

        reasons: list[str] = []
        if not passed_pb:
            reasons.append("PoseBusters geometry/clash failure")
        if not ring_prof.passed:
            reasons.append(
                f"Saturated-ring strain {ring_prof.max_ring_strain_kcal:.2f} kcal/mol "
                f"(> {self.ring_strain_threshold_kcal:.1f})"
            )
        if not tors_prof.passed:
            reasons.append(
                f"Torsion strain (red={tors_prof.n_red}, "
                f"max_barrier={tors_prof.max_local_barrier_kcal:.2f} kcal/mol)"
            )
        if not micro.passed:
            reasons.append(
                "pH 7.4 microstate/tautomer violation ("
                + (", ".join(micro.electrostatic_warnings[:2]) or "mismatch")
                + ")"
            )
        if not passed_inter:
            reasons.append("Canonical 3D pharmacophore anchor not engaged")
        if not passed_hygiene:
            reasons.append(f"MedChem hygiene/reagent alert ({len(all_triage_alerts)} alerts)")
        if not prop_res.passed:
            reasons.append(f"Property profile {prop_res.profile_name!r} violation")
        if not admet_ok:
            reasons.append("Avoid-ome / ADMET safety gate failed")

        # Beyond-PoseBusters physical verdict = Axes 1 + 2 + 3 + 4
        passed_phys = passed_pb and ring_prof.passed and tors_prof.passed and micro.passed
        passed_all = (
            passed_phys and passed_inter and passed_hygiene and prop_res.passed and admet_ok
        )

        # Smooth composite reality_score in [0, 1]
        ring_term = math.exp(
            -max(0.0, ring_prof.max_ring_strain_kcal) / max(0.5, self.ring_strain_threshold_kcal)
        )
        tors_term = (0.75**tors_prof.n_red) * math.exp(
            -max(0.0, tors_prof.max_local_barrier_kcal)
            / max(0.5, self.torsion_barrier_threshold_kcal)
        )
        micro_term = 1.0 if micro.passed else 0.35
        pb_term = 1.0 if passed_pb else 0.20
        inter_term = 1.0 if passed_inter else 0.40
        reality = (
            0.22 * pb_term
            + 0.22 * ring_term
            + 0.18 * tors_term
            + 0.13 * micro_term
            + 0.10 * inter_term
            + 0.15 * (float(triage.hygiene_gate) * (0.5 + 0.5 * prop_res.score))
        )

        return PoseAuditReport(
            name=name,
            smiles=can_smi,
            passed_posebusters=passed_pb,
            posebusters_details=pb_dict,
            passed_ring_strain=ring_prof.passed,
            ring_strain=ring_prof.to_dict(),
            passed_torsion_strain=tors_prof.passed,
            torsion_strain=tors_prof.to_dict(),
            passed_microstate=micro.passed,
            microstate=micro.to_dict(),
            passed_interactions=passed_inter,
            interactions_summary=inter_summary,
            passed_hygiene=passed_hygiene,
            hygiene_gate=float(triage.hygiene_gate),
            hygiene_alerts=all_triage_alerts,
            property_profile=prop_res.to_dict(),
            admet_summary=admet_dict,
            passed_physical_beyond_pb=passed_phys,
            passed_all_7_axes=passed_all,
            reality_score=float(max(0.0, min(1.0, reality))),
            failure_reasons=tuple(reasons),
        )

    def audit_batch(
        self,
        items: Sequence[tuple[str, Chem.Mol | str | Path, str | Path | None]],
        *,
        canonical_anchors_by_name: dict[str, Sequence[str]] | None = None,
    ) -> list[PoseAuditReport]:
        """Audit a batch of ``(name, pose, pocket_pdb)`` complexes deterministically."""
        anchors_map = canonical_anchors_by_name or {}
        return [
            self.audit(
                pose,
                pocket_pdb=pocket,
                name=label,
                canonical_anchors=anchors_map.get(label, ()),
            )
            for label, pose, pocket in items
        ]


def audit_complex(
    pose: Chem.Mol | str | Path,
    pocket_pdb: str | Path | None = None,
    *,
    name: str = "pose",
    property_profile: str = "oral_ro5",
    canonical_anchors: Sequence[str] = (),
    admet_suite: CNSAdmetSuite | None = None,
    ring_strain_threshold_kcal: float = 3.0,
    torsion_barrier_threshold_kcal: float = 2.5,
    strict_input_charge: bool = False,
    seed: int = 42,
) -> PoseAuditReport:
    """One-line Beyond-PoseBusters 7-axis physical & MedChem audit for any 3D complex."""
    auditor = PoseRealityAuditor(
        ring_strain_threshold_kcal=ring_strain_threshold_kcal,
        torsion_barrier_threshold_kcal=torsion_barrier_threshold_kcal,
        strict_input_charge=strict_input_charge,
        property_profile=property_profile,
        admet_suite=admet_suite,
        seed=seed,
    )
    return auditor.audit(
        pose,
        pocket_pdb=pocket_pdb,
        name=name,
        canonical_anchors=canonical_anchors,
    )


def summarize_audit_batch(reports: Sequence[PoseAuditReport]) -> dict[str, Any]:
    """Compute aggregate Beyond-PoseBusters attrition funnel statistics over audited complexes."""
    n = len(reports)
    if n == 0:
        return {"n_audited": 0}
    pb_pass = [r for r in reports if r.passed_posebusters]
    pb_but_fail_beyond = [r for r in pb_pass if not r.passed_physical_beyond_pb]
    return {
        "n_audited": n,
        "posebusters_pass_rate": round(len(pb_pass) / n, 4),
        "ring_strain_pass_rate": round(sum(1 for r in reports if r.passed_ring_strain) / n, 4),
        "torsion_strain_pass_rate": round(
            sum(1 for r in reports if r.passed_torsion_strain) / n, 4
        ),
        "microstate_pass_rate": round(sum(1 for r in reports if r.passed_microstate) / n, 4),
        "hygiene_pass_rate": round(sum(1 for r in reports if r.passed_hygiene) / n, 4),
        "beyond_pb_physical_pass_rate": round(
            sum(1 for r in reports if r.passed_physical_beyond_pb) / n, 4
        ),
        "all_7_axes_pass_rate": round(sum(1 for r in reports if r.passed_all_7_axes) / n, 4),
        "pb_passing_but_failed_beyond_pb_count": len(pb_but_fail_beyond),
        "pb_passing_but_failed_beyond_pb_rate": round(
            len(pb_but_fail_beyond) / max(len(pb_pass), 1), 4
        ),
        "mean_reality_score": round(sum(r.reality_score for r in reports) / n, 4),
    }


def export_audit_json(reports: Sequence[PoseAuditReport], out_path: str | Path) -> Path:
    """Write batch audit reports + aggregate attrition summary to JSON."""
    dest = Path(out_path)
    dest.parent.mkdir(parents=True, exist_ok=True)
    payload = {
        "summary": summarize_audit_batch(reports),
        "reports": [r.to_dict() for r in reports],
    }
    dest.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    return dest



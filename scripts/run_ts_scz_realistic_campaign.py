def _dock_one_candidate_worker(task: dict[str, Any]) -> dict[str, Any]:
    """Run chair-seeded pH 7.4 conformer seeding + real AutoDock Vina v1.2.7 in a worker."""
    smiles: str = task["smiles"]
    target_id: str = task["target_id"]
    pocket_pdb = Path(task["pocket_pdb"])
    rec_pdbqt = Path(task["rec_pdbqt"])
    box_center: tuple[float, float, float] = tuple(task["box_center"])
    box_size: tuple[float, float, float] = tuple(task["box_size"])
    vina_bin = Path(task["vina_bin"])
    exhaustiveness: int = int(task["exhaustiveness"])
    num_modes: int = int(task["num_modes"])
    cpu: int = int(task["cpu"])
    seed: int = int(task["seed"])

    t0 = time.perf_counter()
    chair_seed = seed_chair_conformers_ph74(
        smiles,
        seed=seed,
        num_confs=32,
        max_chair_confs=2,
        ring_strain_cutoff_kcal=2.0,
        energy_window_kcal=1.5,
    )
    if not chair_seed.conformers:
        return {
            "target_id": target_id,
            "smiles": smiles,
            "success": False,
            "error": "Chair conformer seeding failed",
            "elapsed_sec": round(time.perf_counter() - t0, 2),
        }

    mol_prot = protonate_mol_ph74(Chem.MolFromSmiles(smiles), preserve_coords=False)
    pooled: list[tuple[float, Chem.Mol]] = []
    for conf_mol, _mmff_e, _rs in chair_seed.conformers:
        modes = _run_vina_single_conformer(
            conf_mol,
            mol_prot,
            rec_pdbqt,
            box_center,
            box_size,
            vina_exe=vina_bin,
            exhaustiveness=exhaustiveness,
            num_modes=num_modes,
            cpu=cpu,
            seed=seed,
            timeout=180,
        )
        pooled.extend(modes)

    ranked = _deduplicate_modes(pooled, rmsd_tol=0.5, max_keep=num_modes)
    if not ranked:
        return {
            "target_id": target_id,
            "smiles": smiles,
            "success": False,
            "error": "AutoDock Vina returned no valid modes",
            "elapsed_sec": round(time.perf_counter() - t0, 2),
        }

    mode_blocks: list[tuple[float, str]] = [
        (float(aff), str(Chem.MolToMolBlock(mol_m))) for aff, mol_m in ranked
    ]

    # Parallel 6-axis + property-profile audit inside worker (admet_v4_pass confirmed in main)
    canonical_anchors: tuple[str, ...] = tuple(task["canonical_anchors"])
    worker_auditor = PoseRealityAuditor(
        ring_strain_threshold_kcal=3.0,
        ring_n_ref_confs=24,
        torsion_barrier_threshold_kcal=2.5,
        torsion_max_red=0,
        strict_input_charge=False,
        property_profile="cns_mpo_v2",
        admet_suite=None,
        seed=seed,
    )
    top1_dg, top1_block = mode_blocks[0]
    try:
        top1_rep = worker_auditor.audit(
            top1_block,
            pocket_pdb=pocket_pdb,
            name=f"{target_id}_top1",
            canonical_anchors=canonical_anchors,
        )
    except Exception as exc:
        return {
            "target_id": target_id,
            "smiles": smiles,
            "success": False,
            "error": f"PoseRealityAuditor failed: {exc}",
            "elapsed_sec": round(time.perf_counter() - t0, 2),
        }
    best_rank = 1
    best_dg = top1_dg
    best_block = top1_block
    best_rep = top1_rep
    if not top1_rep.passed_all_7_axes:
        for m_idx, (aff_m, blk_m) in enumerate(mode_blocks[1:], start=2):
            try:
                rep_m = worker_auditor.audit(
                    blk_m,
                    pocket_pdb=pocket_pdb,
                    name=f"{target_id}_mode{m_idx}",
                    canonical_anchors=canonical_anchors,
                )
            except Exception:
                continue
            better = (
                (rep_m.passed_all_7_axes and not best_rep.passed_all_7_axes)
                or (
                    rep_m.passed_all_7_axes == best_rep.passed_all_7_axes
                    and rep_m.passed_physical_beyond_pb
                    and not best_rep.passed_physical_beyond_pb
                )
                or (
                    rep_m.passed_all_7_axes == best_rep.passed_all_7_axes
                    and rep_m.passed_physical_beyond_pb == best_rep.passed_physical_beyond_pb
                    and rep_m.passed_interactions
                    and not best_rep.passed_interactions
                )
            )
            if better:
                best_rank = m_idx
                best_dg = aff_m
                best_block = blk_m
                best_rep = rep_m
                if best_rep.passed_all_7_axes:
                    break

    return {
        "target_id": target_id,
        "smiles": smiles,
        "smiles_ph74": chair_seed.smiles_ph74,
        "net_charge_ph74": chair_seed.net_charge_ph74,
        "success": True,
        "n_confs_embedded": chair_seed.n_embedded,
        "n_twist_boat_or_strained_rejected": chair_seed.n_rejected_twist_boat_or_strained,
        "n_chair_confs_docked": len(chair_seed.conformers),
        "seed_ring_strain_kcal": round(chair_seed.best_ring_strain_kcal, 3),
        "seed_pucker_classes": chair_seed.best_pucker_classes,
        "top1_dg": float(top1_dg),
        "top1_report": top1_rep,
        "best_rank": int(best_rank),
        "best_dg": float(best_dg),
        "best_block": best_block,
        "best_report": best_rep,
        "pocket_pdb": str(pocket_pdb),
        "elapsed_sec": round(time.perf_counter() - t0, 2),
    }


def _save_flagship_sdf(
    mol_block: str,
    out_path: Path,
    props: dict[str, Any],
) -> Path:
    """Write a clean, compact, annotated 3D SDF pose for a flagship audited lead."""
    mol = Chem.MolFromMolBlock(mol_block, sanitize=True, removeHs=False)
    if mol is None or mol.GetNumConformers() == 0:
        raise ValueError("Invalid 3D molblock for SDF export.")
    for k, v in props.items():
        if v is not None:
            mol.SetProp(str(k), str(v))
    out_path.parent.mkdir(parents=True, exist_ok=True)
    writer = Chem.SDWriter(str(out_path))
    writer.write(mol)
    writer.close()
    return out_path



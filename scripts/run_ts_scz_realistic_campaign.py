class ChEMBLNoveltyIndex:
    """Fast exact ECFP4 (2048-bit) nearest-neighbor Tanimoto index over curated human ChEMBL."""

    def __init__(self) -> None:
        self._all_fps: list[DataStructs.ExplicitBitVect] = []
        self._all_ids: list[str] = []
        self._by_target_fps: dict[str, list[DataStructs.ExplicitBitVect]] = {}
        self._by_target_ids: dict[str, list[str]] = {}
        self.n_unique_total: int = 0

    @classmethod
    def from_csvs(cls, csv_paths: Sequence[Path]) -> ChEMBLNoveltyIndex:
        idx = cls()
        seen_global: dict[str, str] = {}
        by_target: dict[str, dict[str, str]] = {}

        for csv_path in csv_paths:
            if not csv_path.is_file():
                continue
            df = pd.read_csv(csv_path)
            tcol = "target_symbol" if "target_symbol" in df.columns else "target_id"
            scol = "canonical_smiles" if "canonical_smiles" in df.columns else "SMILES"
            idcol = "molecule_chembl_id" if "molecule_chembl_id" in df.columns else None
            for row in df.itertuples(index=False):
                raw_smi = str(getattr(row, scol, "")).strip()
                if not raw_smi or raw_smi == "nan":
                    continue
                tgt = str(getattr(row, tcol, "")).strip().upper()
                cid = str(getattr(row, idcol, "CHEMBL")) if idcol else "CHEMBL"
                if raw_smi not in seen_global:
                    seen_global[raw_smi] = cid
                by_target.setdefault(tgt, {}).setdefault(raw_smi, cid)

        fp_cache: dict[str, DataStructs.ExplicitBitVect] = {}
        for smi, cid in seen_global.items():
            mol = Chem.MolFromSmiles(smi)
            if mol is None:
                continue
            fp = _MORGAN_2048.GetFingerprint(mol)
            fp_cache[smi] = fp
            idx._all_fps.append(fp)
            idx._all_ids.append(cid)

        for tgt, smi_map in by_target.items():
            t_fps: list[DataStructs.ExplicitBitVect] = []
            t_ids: list[str] = []
            for smi, cid in smi_map.items():
                if smi in fp_cache:
                    t_fps.append(fp_cache[smi])
                    t_ids.append(cid)
            idx._by_target_fps[tgt] = t_fps
            idx._by_target_ids[tgt] = t_ids

        idx.n_unique_total = len(idx._all_fps)
        return idx

    def query(self, smiles: str, target_id: str) -> dict[str, Any]:
        """Return nearest global & per-target ChEMBL ECFP4 Tanimoto similarity."""
        mol = Chem.MolFromSmiles(smiles)
        if mol is None:
            return {
                "nearest_chembl_tanimoto": 1.0,
                "nearest_chembl_id": None,
                "nearest_target_chembl_tanimoto": 1.0,
                "nearest_target_chembl_id": None,
            }
        q_fp = _MORGAN_2048.GetFingerprint(mol)
        global_tan = 0.0
        global_id: str | None = None
        if self._all_fps:
            sims = DataStructs.BulkTanimotoSimilarity(q_fp, self._all_fps)
            best_i = int(np.argmax(sims))
            global_tan = float(sims[best_i])
            global_id = self._all_ids[best_i]

        tgt_tan = 0.0
        tgt_id: str | None = None
        t_fps = self._by_target_fps.get(target_id.upper(), [])
        if t_fps:
            t_sims = DataStructs.BulkTanimotoSimilarity(q_fp, t_fps)
            best_t = int(np.argmax(t_sims))
            tgt_tan = float(t_sims[best_t])
            tgt_id = self._by_target_ids[target_id.upper()][best_t]

        return {
            "nearest_chembl_tanimoto": round(global_tan, 4),
            "nearest_chembl_id": global_id,
            "nearest_target_chembl_tanimoto": round(tgt_tan, 4),
            "nearest_target_chembl_id": tgt_id,
        }



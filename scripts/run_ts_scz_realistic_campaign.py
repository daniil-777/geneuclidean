def build_realistic_candidate_pool(
    cfg: CampaignTargetConfig,
    existing_denovo: Sequence[dict[str, Any]],
    *,
    admet_suite: CNSAdmetSuite | None,
    chembl_index: ChEMBLNoveltyIndex | None = None,
    exclude_smiles: set[str] | None = None,
    max_dock_candidates: int = 8,
    min_cns_mpo_v2: float = 4.2,
    max_sa_score: float = 4.0,
    max_rotatable_bonds: int = 7,
) -> tuple[list[dict[str, Any]], dict[str, Any]]:
    """Run makeable enumeration, Avoid-ome MMP rescue, and MedChem/MPO triage for one target."""
    pool: dict[str, dict[str, Any]] = {}

    # Collect clinical reference canonical SMILES so we never select an exact reference drug
    spec = ALL_CNS_TARGET_REGISTRY.get(cfg.target_id) or TOURETTE_CIRCUIT_EXPANSION_REGISTRY.get(
        cfg.target_id
    )
    clinical_set: set[str] = set()
    if spec is not None:
        for ref in spec.reference_drugs:
            rm = Chem.MolFromSmiles(ref.canonical_smiles)
            if rm is not None:
                clinical_set.add(str(Chem.MolToSmiles(rm, canonical=True, isomericSmiles=False)))

    # 1. Existing v3.1 / v4.0 / TS-circuit de novo candidates
    for item in existing_denovo:
        smi = str(item["smiles"])
        pool[smi] = dict(item)
    n_denovo_raw = len(pool)

    # 2. Fresh 1-step makeable reaction analogs via enumerate_makeable_analogs
    lib = MAKEABLE_LIBRARY_BY_CLASS[cfg.pharmacophore_class]
    n_makeable_raw = 0
    for core_smi in lib["cores"]:
        analogs = enumerate_makeable_analogs(
            core_smi,
            lib["building_blocks"],
            reactions=lib["reactions"],
            max_products=60,
            triage_filter=True,
        )
        for cand in analogs:
            n_makeable_raw += 1
            if cand.product_smiles not in pool:
                pool[cand.product_smiles] = {
                    "smiles": cand.product_smiles,
                    "source_stage": "makeable_1step",
                    "origin_detail": cand.reaction_name,
                    "makeable_provenance": cand.to_dict(),
                }

    # 3. Pre-score seeds and apply AvoidomeMMPEngine 1-cut bioisostere rescues
    mmp_engine = AvoidomeMMPEngine(admet_suite=admet_suite, property_profile="cns_mpo_v2")
    # Rescue ALL existing de novo candidates + top 12 makeable candidates by MPO
    mmp_seeds: list[str] = [item["smiles"] for item in existing_denovo]
    makeable_scored: list[tuple[float, str]] = []
    for smi, meta in pool.items():
        if meta["source_stage"] == "makeable_1step":
            mpo = compute_cns_mpo(smi)
            if mpo.valid and mpo.cns_mpo_v2 >= min_cns_mpo_v2 and mpo.sa_score <= max_sa_score:
                makeable_scored.append((mpo.cns_mpo_v2, smi))
    makeable_scored.sort(key=lambda x: (-x[0], x[1]))
    mmp_seeds.extend(s for _, s in makeable_scored[:12])

    n_mmp_raw = 0
    mmp_herg_gains: list[float] = []
    mmp_htr2b_gains: list[float] = []
    mmp_mdr1_gains: list[float] = []
    for seed_smi in mmp_seeds:
        try:
            proposals = mmp_engine.propose_rescues(seed_smi, max_proposals=12, triage_filter=True)
        except Exception:
            continue
        for prop in proposals:
            n_mmp_raw += 1
            if prop.delta_herg_reduction is not None and prop.delta_herg_reduction > 0:
                mmp_herg_gains.append(prop.delta_herg_reduction)
            if prop.delta_htr2b_reduction is not None and prop.delta_htr2b_reduction > 0:
                mmp_htr2b_gains.append(prop.delta_htr2b_reduction)
            if prop.delta_mdr1_reduction is not None and prop.delta_mdr1_reduction > 0:
                mmp_mdr1_gains.append(prop.delta_mdr1_reduction)
            if prop.analog_smiles not in pool:
                pool[prop.analog_smiles] = {
                    "smiles": prop.analog_smiles,
                    "source_stage": "mmp_rescue",
                    "origin_detail": f"mmp:{prop.transform_name}",
                    "mmp_provenance": prop.to_dict(),
                }

    # 4. Strict MedChem Triage + CNS MPO v2 + SA + RotB + Pharmacophore Pre-Filter
    prefiltered: list[dict[str, Any]] = []
    for smi, meta in pool.items():
        mol = Chem.MolFromSmiles(smi)
        if mol is None:
            continue
        flat = str(Chem.MolToSmiles(mol, canonical=True, isomericSmiles=False))
        if flat in clinical_set:
            continue
        triage = triage_molecule(mol)
        if not (triage.pains_free and triage.brenk_free and triage.triage_pass):
            continue
        mpo = compute_cns_mpo(mol)
        if not mpo.valid:
            continue
        if mpo.sa_score > max_sa_score:
            continue
        if mpo.cns_mpo_v2 < min_cns_mpo_v2:
            continue
        if mpo.tpsa > 90.0 or mpo.mw < 170.0 or mpo.mw > 450.0:
            continue
        rot_b = int(rdMolDescriptors.CalcNumRotatableBonds(mol))
        if rot_b > max_rotatable_bonds:
            continue

        # Target-appropriate protonation: aminergic GPCRs & VMAT2 engage Asp3.32/Glu312 via [NH+]
        prot = protonate_mol_ph74(mol, preserve_coords=False)
        net_q = int(Chem.GetFormalCharge(prot))
        if (
            cfg.pharmacophore_class
            in (
                "aminergic_antagonist",
                "serotonergic_htr2a",
                "compact_aminergic_agonist",
                "vmat2_inhibitor",
            )
            and net_q <= 0
            and meta["source_stage"] != "denovo_v4_v5"
        ):
            continue

        # Verify deterministic pH 7.4 tautomer microstate enumeration succeeds cleanly
        try:
            taut_chk = audit_tautomer_microstate_ph74(mol)
            if not taut_chk.tautomer_plausible:
                continue
        except Exception:
            continue

        retro = match_one_step_retrosynthesis(smi)
        entry = {
            **meta,
            "mw": round(float(mpo.mw), 2),
            "clogp": round(float(mpo.clogp), 3),
            "tpsa": round(float(mpo.tpsa), 2),
            "hbd": int(mpo.hbd),
            "hba": int(mpo.hba),
            "most_basic_pka": round(float(mpo.most_basic_pka), 2),
            "cns_mpo_v2": round(float(mpo.cns_mpo_v2), 3),
            "qed": round(float(mpo.qed), 4),
            "sa_score": round(float(mpo.sa_score), 3),
            "rotatable_bonds": rot_b,
            "net_charge_ph74": net_q,
            "triage_pass": True,
            "pains_count": len(triage.pains_alerts),
            "brenk_count": len(triage.brenk_alerts),
            "lilly_demerit_score": int(triage.lilly_demerit_score),
            "exact_murcko_scaffold": triage.exact_murcko_scaffold,
            "retrosynthesis_1step": retro,
            "is_1step_makeable": bool(
                meta.get("makeable_provenance") is not None or retro.get("is_solved", False)
            ),
        }
        prefiltered.append(entry)

    # 5. Batch 12-Endpoint Calibrated Avoid-ome Scoring
    n_admet_pass = 0
    if prefiltered and admet_suite is not None and len(admet_suite.fitted_endpoints) > 3:
        preds = admet_suite.predict_v4([e["smiles"] for e in prefiltered])
        for entry, pred in zip(prefiltered, preds, strict=True):
            probs = {k: round(float(v), 4) for k, v in pred.probabilities.items()}
            entry["avoidome_12ep"] = probs
            entry["admet_v4_pass"] = bool(pred.admet_v4_pass)
            if pred.admet_v4_pass:
                n_admet_pass += 1
    else:
        for entry in prefiltered:
            entry["avoidome_12ep"] = {}
            entry["admet_v4_pass"] = True
            n_admet_pass += 1

    # 6. Rank by multi-objective CNS realism + Avoid-ome safety + makeability
    def _pre_dock_score(e: dict[str, Any]) -> float:
        probs = e["avoidome_12ep"]
        herg = float(probs.get("herg", 0.2))
        htr2b = float(probs.get("htr2b_avoid", 0.1))
        mdr1 = float(probs.get("mdr1_efflux", 0.2))
        bbb = float(probs.get("bbb", 0.9))
        chrm3 = float(probs.get("chrm3_avoid", 0.1))
        admet_bonus = 1.5 if e["admet_v4_pass"] else 0.0
        make_bonus = 0.25 if e["is_1step_makeable"] else 0.0
        # Target-specific MW sweet spot (compact agonists vs larger orthosteric pockets)
        mw = float(e["mw"])
        if cfg.pharmacophore_class == "compact_aminergic_agonist":
            mw_term = 0.35 if 185.0 <= mw <= 315.0 else -0.25
        else:
            mw_term = 0.35 if 240.0 <= mw <= 390.0 else 0.0
        m3_pen = 0.5 * chrm3 if cfg.target_id in ("CHRM1", "CHRM4") else 0.0
        return (
            admet_bonus
            + make_bonus
            + mw_term
            + 0.45 * (float(e["cns_mpo_v2"]) / 6.0)
            + 0.30 * bbb
            - 0.60 * herg
            - 0.50 * htr2b
            - 0.40 * mdr1
            - m3_pen
            - 0.08 * float(e["sa_score"])
            - 0.05 * float(e["rotatable_bonds"])
        )

    prefiltered.sort(key=lambda e: (-_pre_dock_score(e), e["smiles"]))

    # 7. Select diverse top candidates ensuring representation across sources + ChEMBL novelty
    selected: list[dict[str, Any]] = []
    selected_fps: list[DataStructs.ExplicitBitVect] = []
    excluded = exclude_smiles or set()

    def _try_add(cand: dict[str, Any], max_sim: float, *, allow_excluded: bool = False) -> bool:
        if len(selected) >= max_dock_candidates:
            return False
        if (not allow_excluded) and cand["smiles"] in excluded:
            return False
        if any(s["smiles"] == cand["smiles"] for s in selected):
            return False
        mol = Chem.MolFromSmiles(cand["smiles"])
        if mol is None:
            return False
        fp = _MORGAN_2048.GetFingerprint(mol)
        if selected_fps and max(DataStructs.BulkTanimotoSimilarity(fp, selected_fps)) > max_sim:
            return False
        if chembl_index is not None:
            nov = chembl_index.query(cand["smiles"], cfg.target_id)
            if nov["nearest_chembl_tanimoto"] >= 0.99:
                return False
            cand["chembl_novelty"] = nov
        else:
            cand["chembl_novelty"] = {
                "nearest_chembl_tanimoto": None,
                "nearest_chembl_id": None,
                "nearest_target_chembl_tanimoto": None,
                "nearest_target_chembl_id": None,
            }
        selected.append(cand)
        selected_fps.append(fp)
        return True

    # Ensure balanced quota from all three stages (strictly preferring admet_v4_pass first)
    for stage_name, quota in (("makeable_1step", 3), ("mmp_rescue", 3), ("denovo_v4_v5", 2)):
        added = 0
        for cand_entry in prefiltered:
            if (
                cand_entry["source_stage"] == stage_name
                and cand_entry["admet_v4_pass"]
                and _try_add(cand_entry, max_sim=0.72)
            ):
                added += 1
                if added >= quota:
                    break
    # Fill remaining slots from any passing candidate (preferring globally novel, then relaxed sim)
    for allow_ex in (False, True):
        for max_sim in (0.72, 0.85, 0.95):
            for cand_entry in prefiltered:
                if len(selected) >= max_dock_candidates:
                    break
                if cand_entry["admet_v4_pass"]:
                    _try_add(cand_entry, max_sim=max_sim, allow_excluded=allow_ex)
    # Final fallback if target had < max_dock_candidates passing strict admet_v4_pass
    for cand_entry in prefiltered:
        if len(selected) >= max_dock_candidates:
            break
        _try_add(cand_entry, max_sim=0.85, allow_excluded=True)

    funnel = {
        "n_existing_denovo_harvested": n_denovo_raw,
        "n_makeable_1step_enumerated": n_makeable_raw,
        "n_mmp_rescues_proposed": n_mmp_raw,
        "n_unique_pool_total": len(pool),
        "n_passed_strict_medchem_mpo_filter": len(prefiltered),
        "n_passed_12ep_avoidome": n_admet_pass,
        "n_selected_for_vina_docking": len(selected),
        "mmp_mean_herg_reduction_positive": (
            round(float(np.mean(mmp_herg_gains)), 4) if mmp_herg_gains else 0.0
        ),
        "mmp_mean_htr2b_reduction_positive": (
            round(float(np.mean(mmp_htr2b_gains)), 4) if mmp_htr2b_gains else 0.0
        ),
        "mmp_mean_mdr1_reduction_positive": (
            round(float(np.mean(mmp_mdr1_gains)), 4) if mmp_mdr1_gains else 0.0
        ),
    }
    return selected, funnel



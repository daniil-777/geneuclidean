# ---------------------------------------------------------------------------
# Chair-Seeded Conformer Generator (Eliminates twist_boat / boat BEFORE Docking)
# ---------------------------------------------------------------------------


@dataclass
class ChairSeedResult:
    """Chair-seeded physiological pH 7.4 conformers with pre-docking ring-strain stats."""

    smiles: str
    smiles_ph74: str
    net_charge_ph74: int
    conformers: list[tuple[Chem.Mol, float, float]]  # (mol_3d_h, mmff_energy, ring_strain_kcal)
    n_embedded: int
    n_rejected_twist_boat_or_strained: int
    best_ring_strain_kcal: float
    best_pucker_classes: list[str]


def seed_chair_conformers_ph74(
    smiles: str,
    *,
    seed: int = 42,
    num_confs: int = 32,
    max_chair_confs: int = 2,
    ring_strain_cutoff_kcal: float = 2.0,
    energy_window_kcal: float = 1.5,
    ring_rmsd_cutoff: float = 0.28,
    max_iters: int = 400,
) -> ChairSeedResult:
    """Generate lowest-energy pH 7.4 chair conformers, eliminating twist-boat rings BEFORE docking.

    Embeds ``num_confs`` conformers strictly from 2D connectivity via ``ETKDGv3`` +
    ``MMFF94s``, then audits each low-energy conformer with Cremer-Pople ring puckering
    and isolated ring-system strain (:func:`analyze_ring_strain`). Rejects any conformer
    exhibiting ``boat`` or ``twist_boat`` 6-membered rings or ring strain exceeding
    ``ring_strain_cutoff_kcal``.
    """
    mol_2d = Chem.MolFromSmiles(smiles.strip())
    if mol_2d is None:
        raise ValueError(f"Invalid SMILES: {smiles!r}")
    canon_smi = str(Chem.MolToSmiles(mol_2d, canonical=True, isomericSmiles=True))
    mol_prot = protonate_mol_ph74(mol_2d, preserve_coords=False)
    smiles_ph74 = str(Chem.MolToSmiles(mol_prot, canonical=True, isomericSmiles=True))
    net_q = int(Chem.GetFormalCharge(mol_prot))
    mol_h = Chem.AddHs(mol_prot)

    cids: list[int] = []
    for use_random in (False, True):
        params = _ALLCHEM.ETKDGv3()
        params.randomSeed = int(seed)
        params.numThreads = 1
        params.useSmallRingTorsions = True
        params.enforceChirality = True
        params.timeout = 4
        params.useRandomCoords = use_random
        try:
            cids = [
                int(c)
                for c in _ALLCHEM.EmbedMultipleConfs(mol_h, numConfs=num_confs, params=params)
            ]
        except RuntimeError:
            cids = []
        if cids:
            break

    if not cids:
        return ChairSeedResult(
            smiles=canon_smi,
            smiles_ph74=smiles_ph74,
            net_charge_ph74=net_q,
            conformers=[],
            n_embedded=0,
            n_rejected_twist_boat_or_strained=0,
            best_ring_strain_kcal=0.0,
            best_pucker_classes=[],
        )

    energies: list[tuple[int, float]] = []
    if _ALLCHEM.MMFFHasAllMoleculeParams(mol_h):
        props = _ALLCHEM.MMFFGetMoleculeProperties(mol_h, mmffVariant="MMFF94s")
        if props is not None:
            for cid in cids:
                ff = _ALLCHEM.MMFFGetMoleculeForceField(mol_h, props, confId=cid)
                if ff is not None:
                    ff.Minimize(maxIts=max_iters)
                    energies.append((cid, float(ff.CalcEnergy())))
    if not energies and _ALLCHEM.UFFHasAllMoleculeParams(mol_h):
        for cid in cids:
            ff = _ALLCHEM.UFFGetMoleculeForceField(mol_h, confId=cid)
            if ff is not None:
                ff.Minimize(maxIts=max_iters)
                energies.append((cid, float(ff.CalcEnergy())))
    if not energies:
        energies = [(cid, 0.0) for cid in cids]

    energies.sort(key=lambda item: item[1])
    ring_systems = _extract_fused_ring_systems(mol_h)

    selected: list[tuple[int, Chem.Mol, float, float, list[str]]] = []
    fallback: tuple[int, Chem.Mol, float, float, list[str]] | None = None
    n_rejected = 0
    min_accepted_e: float | None = None

    for cid, e_val in energies:
        if min_accepted_e is not None and (e_val - min_accepted_e) > energy_window_kcal:
            break
        single = Chem.Mol(mol_h)
        single.RemoveAllConformers()
        single.AddConformer(mol_h.GetConformer(cid), assignId=True)

        prof = analyze_ring_strain(
            single,
            strain_threshold_kcal=ring_strain_cutoff_kcal,
            n_ref_confs=16,
            include_full_ligand_strain=False,
            seed=seed,
        )
        puckers = [r.pucker_class for r in prof.rings]
        has_bad_pucker = any(
            r.ring_size == 6 and r.pucker_class in ("boat", "twist_boat") for r in prof.rings
        )
        is_clean_chair = (not has_bad_pucker) and (
            prof.max_ring_strain_kcal <= ring_strain_cutoff_kcal
        )

        if fallback is None or prof.max_ring_strain_kcal < fallback[3]:
            fallback = (cid, single, e_val, prof.max_ring_strain_kcal, puckers)

        if not is_clean_chair:
            n_rejected += 1
            continue

        if (
            selected
            and ring_systems
            and any(
                _max_ring_system_rmsd(mol_h, cid, prev_cid, ring_systems) < ring_rmsd_cutoff
                for prev_cid, _, _, _, _ in selected
            )
        ):
            continue

        selected.append((cid, single, e_val, prof.max_ring_strain_kcal, puckers))
        if min_accepted_e is None:
            min_accepted_e = e_val
        if len(selected) >= max_chair_confs:
            break

    if not selected and fallback is not None:
        selected.append(fallback)

    return ChairSeedResult(
        smiles=canon_smi,
        smiles_ph74=smiles_ph74,
        net_charge_ph74=net_q,
        conformers=[(m, e, rs) for _, m, e, rs, _ in selected],
        n_embedded=len(energies),
        n_rejected_twist_boat_or_strained=n_rejected,
        best_ring_strain_kcal=selected[0][3] if selected else 0.0,
        best_pucker_classes=selected[0][4] if selected else [],
    )



            pdb_path = pdir / f"{pid}_pocket.pdb"
            sdf_path = pdir / f"{pid}_ligand.sdf"
            if not (_is_locally_materialized(pdb_path) and _is_locally_materialized(sdf_path)):
                continue
            pkd_str = meta.get("value", "").strip()

def collate_complex_batches(
    records: Sequence[RealComplexRecord],
    *,
    use_eval_input: bool,
    max_n: int,
    max_l: int,
    max_b12: int = 56,
    max_b13: int = 112,
    max_chi: int = 16,
) -> ComplexBatch:
    """Pad a list of real complexes into a fixed-shape :class:`ComplexBatch` for cached MPS."""
    batch_size = len(records)
    coords = torch.zeros((batch_size, max_n, 3), dtype=torch.float32)
    atom_feats = torch.zeros((batch_size, max_n, 52), dtype=torch.float32)
    a2t = torch.zeros((batch_size, max_n), dtype=torch.long)
    atom_mask = torch.zeros((batch_size, max_n), dtype=torch.bool)
    token_mask = torch.zeros((batch_size, max_l), dtype=torch.bool)
    chain_id = torch.zeros((batch_size, max_l), dtype=torch.long)
    token_type = torch.zeros((batch_size, max_l), dtype=torch.long)
    res_index = torch.zeros((batch_size, max_l), dtype=torch.long)
    flex_mask = torch.zeros((batch_size, max_n), dtype=torch.bool)
    is_lig = torch.zeros((batch_size, max_n), dtype=torch.bool)
    is_bb = torch.zeros((batch_size, max_n), dtype=torch.bool)
    rep_idx = torch.zeros((batch_size, max_l), dtype=torch.long)
    cov_adj = torch.zeros((batch_size, max_n, max_n, 6), dtype=torch.float32)
    b12_idx = torch.zeros((batch_size, max_b12, 2), dtype=torch.long)
    b12_ref = torch.zeros((batch_size, max_b12), dtype=torch.float32)
    b12_mask = torch.zeros((batch_size, max_b12), dtype=torch.bool)
    b13_idx = torch.zeros((batch_size, max_b13, 2), dtype=torch.long)
    b13_ref = torch.zeros((batch_size, max_b13), dtype=torch.float32)
    b13_mask = torch.zeros((batch_size, max_b13), dtype=torch.bool)
    chi_q = torch.zeros((batch_size, max_chi, 4), dtype=torch.long)
    chi_vol = torch.zeros((batch_size, max_chi), dtype=torch.float32)
    chi_m = torch.zeros((batch_size, max_chi), dtype=torch.bool)
    pkd = torch.full((batch_size,), float("nan"), dtype=torch.float32)
    is_binder = torch.ones((batch_size,), dtype=torch.float32)
    cent = torch.zeros((batch_size, 3), dtype=torch.float32)

    for i, rec in enumerate(records):
        b = rec.batch_eval_input if use_eval_input else rec.batch_train
        n = int(b.coords.shape[1])
        l_tok = int(b.token_mask.shape[1])
        coords[i, :n] = b.coords[0]
        atom_feats[i, :n] = b.atom_feats[0]
        a2t[i, :n] = b.atom_to_token[0]
        atom_mask[i, :n] = b.atom_mask[0]
        token_mask[i, :l_tok] = b.token_mask[0]
        chain_id[i, :l_tok] = b.chain_id[0]
        token_type[i, :l_tok] = b.token_type[0]
        res_index[i, :l_tok] = b.res_index[0]
        if b.flex_mask is not None:
            flex_mask[i, :n] = b.flex_mask[0]
        if b.is_ligand_atom is not None:
            is_lig[i, :n] = b.is_ligand_atom[0]
        if b.is_backbone_atom is not None:
            is_bb[i, :n] = b.is_backbone_atom[0]
        if b.token_rep_atom_idx is not None:
            rep_idx[i, :l_tok] = b.token_rep_atom_idx[0]
        if b.covalent_adj is not None:
            cov_adj[i, :n, :n] = b.covalent_adj[0]
        if b.bond_12_idx is not None and b.bond_12_ref is not None and b.bond_12_mask is not None:
            e12 = min(int(b.bond_12_idx.shape[1]), max_b12)
            if e12 > 0:
                b12_idx[i, :e12] = b.bond_12_idx[0, :e12]
                b12_ref[i, :e12] = b.bond_12_ref[0, :e12]
                b12_mask[i, :e12] = b.bond_12_mask[0, :e12]
        if b.bond_13_idx is not None and b.bond_13_ref is not None and b.bond_13_mask is not None:
            e13 = min(int(b.bond_13_idx.shape[1]), max_b13)
            if e13 > 0:
                b13_idx[i, :e13] = b.bond_13_idx[0, :e13]
                b13_ref[i, :e13] = b.bond_13_ref[0, :e13]
                b13_mask[i, :e13] = b.bond_13_mask[0, :e13]
        if b.chiral_quads is not None and b.chiral_mask is not None:
            nc = min(int(b.chiral_quads.shape[1]), max_chi)
            if nc > 0:
                chi_q[i, :nc] = b.chiral_quads[0, :nc]
                chi_m[i, :nc] = b.chiral_mask[0, :nc]
                if b.chiral_vol_true is not None:
                    chi_vol[i, :nc] = b.chiral_vol_true[0, :nc]
        if b.pkd_true is not None:
            pkd[i] = b.pkd_true[0]
        if b.centroid_offset is not None:
            cent[i] = b.centroid_offset[0]

    return ComplexBatch(
        coords=coords,
        atom_feats=atom_feats,
        atom_to_token=a2t,
        atom_mask=atom_mask,
        token_mask=token_mask,
        chain_id=chain_id,
        token_type=token_type,
        res_index=res_index,
        flex_mask=flex_mask,
        is_ligand_atom=is_lig,
        is_backbone_atom=is_bb,
        token_rep_atom_idx=rep_idx,
        covalent_adj=cov_adj,
        bond_12_idx=b12_idx,
        bond_12_ref=b12_ref,
        bond_12_mask=b12_mask,
        bond_13_idx=b13_idx,
        bond_13_ref=b13_ref,
        bond_13_mask=b13_mask,
        chiral_quads=chi_q,
        chiral_vol_true=chi_vol,
        chiral_mask=chi_m,
        pkd_true=pkd,
        is_binder_true=is_binder,
        centroid_offset=cent,
    )



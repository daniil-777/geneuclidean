def _compute_interface_smooth_lddt(
    pred_coords: Tensor,
    true_coords: Tensor,
    atom_mask: Tensor,
    is_ligand: Tensor,
) -> float:
    """Compute normalized Smooth LDDT restricted to pairs containing >= 1 ligand atom."""
    # Single complex [N, 3]
    valid = atom_mask.to(torch.bool)
    p = pred_coords[valid]
    t = true_coords[valid]
    lig = is_ligand[valid].to(torch.bool)
    n = int(p.shape[0])
    if n < 2 or not bool(lig.any().item()):
        return 0.0
    d_p = torch.cdist(p.unsqueeze(0), p.unsqueeze(0)).squeeze(0)
    d_t = torch.cdist(t.unsqueeze(0), t.unsqueeze(0)).squeeze(0)
    eye = torch.eye(n, device=p.device, dtype=torch.bool)
    involves_lig = lig.unsqueeze(1) | lig.unsqueeze(0)
    inter = lig.unsqueeze(1) != lig.unsqueeze(0)
    radius_ok = torch.where(inter, d_t < 30.0, d_t < 15.0)
    incl = (~eye) & involves_lig & radius_ok
    if not bool(incl.any().item()):
        return 0.0
    abs_err = (d_p - d_t).abs()
    thresh = torch.tensor([0.5, 1.0, 2.0, 4.0], device=p.device, dtype=torch.float32)
    max_s = float(torch.sigmoid(thresh).mean().item())
    raw = torch.sigmoid(thresh.view(1, 1, 4) - abs_err.unsqueeze(-1)).mean(dim=-1)
    norm = (raw / max_s).clamp(0.0, 1.0)
    return float(norm[incl].mean().item())


def _build_cofolded_mol_and_pocket_pdb(
    rec: RealComplexRecord,
    coords_local_np: np.ndarray,
    plddt_np: np.ndarray,
) -> tuple[Any, str]:
    """Reconstruct 3D RDKit ligand Mol and 80-col pocket PDB from co-folded local coords."""
    n_tot = len(rec.pdb_records)
    coords_world = coords_local_np[:n_tot] + rec.pocket_center_world[None, :]
    plddt_valid = plddt_np[:n_tot]
    lig_start = rec.n_pocket_atoms

    mol_3d = Chem.Mol(rec.ligand_mol_template)
    mol_3d.RemoveAllConformers()
    conf = Chem.Conformer(rec.n_ligand_atoms)
    for i in range(rec.n_ligand_atoms):
        x, y, z = coords_world[lig_start + i]
        conf.SetAtomPosition(i, Point3D(float(x), float(y), float(z)))
    mol_3d.AddConformer(conf, assignId=True)
    pocket_pdb_text = _format_pdb_lines(
        rec.pdb_records, coords_world, plddt_valid, include_ligand=False
    )
    return mol_3d, pocket_pdb_text


def _audit_pose_set(
    poses: Sequence[tuple[str, Any, str | Path]],
    *,
    property_profile: str,
) -> dict[str, Any]:
    """Run canonical 7-axis PoseRealityAuditor over a set of 3D complexes."""
    auditor = PoseRealityAuditor(property_profile=property_profile)
    per_item: list[dict[str, Any]] = []
    failure_counts: dict[str, int] = {}

    for name, mol_3d, pocket_pdb in poses:
        try:
            rep = auditor.audit(mol_3d, pocket_pdb=pocket_pdb, name=name)
            per_item.append(
                {
                    "name": name,
                    "passed_posebusters": bool(rep.passed_posebusters),
                    "passed_ring_strain": bool(rep.passed_ring_strain),
                    "passed_torsion_strain": bool(rep.passed_torsion_strain),
                    "passed_microstate": bool(rep.passed_microstate),
                    "passed_interactions": bool(rep.passed_interactions),
                    "passed_hygiene": bool(rep.passed_hygiene),
                    "passed_property_profile": bool(rep.property_profile.get("passed", False)),
                    "passed_physical_beyond_pb": bool(rep.passed_physical_beyond_pb),
                    "passed_all_7_axes": bool(rep.passed_all_7_axes),
                    "reality_score": round(float(rep.reality_score), 4),
                    "protein_clash_count": int(
                        rep.posebusters_details.get("protein_clash_count", 0)
                    ),
                    "internal_clash_count": int(
                        rep.posebusters_details.get("internal_clash_count", 0)
                    ),
                    "failure_reasons": list(rep.failure_reasons),
                }
            )
            for reason in rep.failure_reasons:
                key = reason.split(":")[0].strip()[:64]
                failure_counts[key] = failure_counts.get(key, 0) + 1
        except Exception as exc:
            per_item.append(
                {
                    "name": name,
                    "error": str(exc)[:160],
                    "passed_posebusters": False,
                    "passed_ring_strain": False,
                    "passed_torsion_strain": False,
                    "passed_microstate": False,
                    "passed_interactions": False,
                    "passed_hygiene": False,
                    "passed_property_profile": False,
                    "passed_physical_beyond_pb": False,
                    "passed_all_7_axes": False,
                    "reality_score": 0.0,
                }
            )
            failure_counts["audit_exception"] = failure_counts.get("audit_exception", 0) + 1

    n = max(len(per_item), 1)
    top_failures = sorted(failure_counts.items(), key=lambda kv: (-kv[1], kv[0]))[:6]
    return {
        "n_audited": len(per_item),
        "property_profile": property_profile,
        "posebusters_pass_rate": round(sum(x["passed_posebusters"] for x in per_item) / n, 4),
        "ring_strain_pass_rate": round(sum(x["passed_ring_strain"] for x in per_item) / n, 4),
        "torsion_strain_pass_rate": round(sum(x["passed_torsion_strain"] for x in per_item) / n, 4),
        "microstate_pass_rate": round(sum(x["passed_microstate"] for x in per_item) / n, 4),
        "interactions_pass_rate": round(sum(x["passed_interactions"] for x in per_item) / n, 4),
        "hygiene_pass_rate": round(sum(x["passed_hygiene"] for x in per_item) / n, 4),
        "physical_beyond_pb_pass_rate": round(
            sum(x["passed_physical_beyond_pb"] for x in per_item) / n, 4
        ),
        "all_7_axes_pass_rate": round(sum(x["passed_all_7_axes"] for x in per_item) / n, 4),
        "mean_reality_score": round(
            float(np.mean([float(x["reality_score"]) for x in per_item])), 4
        ),
        "top_failure_reasons": [{"reason": k, "count": v} for k, v in top_failures],
        "per_complex": per_item,
    }


@torch.inference_mode()
def evaluate_model_on_records(
    model: NanoFold3,
    records: Sequence[RealComplexRecord],
    device: torch.device,
    *,
    max_n: int,
    max_l: int,
    batch_size: int = 8,
    num_steps: int = 16,
    seed: int = 42,
    run_pose_audit: bool = False,
    audit_limit: int | None = None,
    property_profile: str = "oral_ro5",
    include_per_complex: bool = False,
) -> dict[str, Any]:
    """Evaluate a NanoFold3 model strictly without crystal ligand coordinate leakage."""
    model.eval()
    kabsch = KabschWeightedRigidAlign().to(device)

    kabsch_rmsds: list[float] = []
    unaligned_rmsds: list[float] = []
    complex_lddts: list[float] = []
    interface_lddts: list[float] = []
    bond_maes: list[float] = []
    clash_rates: list[float] = []
    pl_clash_counts: list[int] = []
    chiral_total = 0
    chiral_preserved = 0
    chiral_vol_errs: list[float] = []
    plddt_means: list[float] = []
    lig_plddts: list[float] = []
    iptms: list[float] = []
    ptms: list[float] = []
    rankings: list[float] = []
    pred_pkds: list[float] = []
    true_pkds: list[float] = []
    per_complex_rows: list[dict[str, Any]] = []
    audit_inputs: list[tuple[str, Any, str | Path]] = []

    t0 = time.perf_counter()
    for start in range(0, len(records), batch_size):
        chunk = records[start : start + batch_size]
        b_true = collate_complex_batches(chunk, use_eval_input=False, max_n=max_n, max_l=max_l).to(
            device
        )
        b_in = collate_complex_batches(chunk, use_eval_input=True, max_n=max_n, max_l=max_l).to(
            device
        )

        sample_out = model.sample(
            b_in,
            num_steps=num_steps,
            num_samples=1,
            flex_mode="flexible_pocket_and_ligand",
            seed=seed + start,
        )
        pred = sample_out.coords[0]  # [B, N, 3]
        conf = sample_out.confidence

        for i, rec in enumerate(chunk):
            am = b_true.atom_mask[i]
            lm = b_true.is_ligand_atom[i] & am if b_true.is_ligand_atom is not None else am
            p_lig = pred[i, lm]
            t_lig = b_true.coords[i, lm]

            u_rmsd = float(torch.sqrt(((p_lig - t_lig) ** 2).sum(dim=-1).mean()).item())
            w_lig = torch.ones((1, int(p_lig.shape[0])), device=device, dtype=torch.float32)
            p_aligned, _, _ = kabsch(p_lig.unsqueeze(0), t_lig.unsqueeze(0), w_lig)
            k_rmsd = float(torch.sqrt(((p_aligned[0] - t_lig) ** 2).sum(dim=-1).mean()).item())
            kabsch_rmsds.append(k_rmsd)
            unaligned_rmsds.append(u_rmsd)

            # Smooth LDDT: full complex & ligand-interface.
            d_p = torch.cdist(pred[i : i + 1], pred[i : i + 1])
            d_t = torch.cdist(b_true.coords[i : i + 1], b_true.coords[i : i + 1])
            c_lddt_loss = model.cofolding_loss._compute_smooth_lddt(
                d_p,
                d_t,
                b_true.atom_mask[i : i + 1],
                b_true.is_ligand_atom[i : i + 1] if b_true.is_ligand_atom is not None else None,
            )
            c_lddt = float(1.0 - c_lddt_loss.item())
            i_lddt = _compute_interface_smooth_lddt(
                pred[i],
                b_true.coords[i],
                am,
                b_true.is_ligand_atom[i] if b_true.is_ligand_atom is not None else am,
            )
            complex_lddts.append(c_lddt)
            interface_lddts.append(i_lddt)

            # 1-2 Covalent bond-length MAE.
            bond_mae_i = float("nan")
            if (
                b_true.bond_12_idx is not None
                and b_true.bond_12_ref is not None
                and b_true.bond_12_mask is not None
            ):
                bm = b_true.bond_12_mask[i]
                if bool(bm.any().item()):
                    b_idx = b_true.bond_12_idx[i, bm]
                    d_b = torch.linalg.norm(pred[i, b_idx[:, 0]] - pred[i, b_idx[:, 1]], dim=-1)
                    d_r = b_true.bond_12_ref[i, bm]
                    bond_mae_i = float((d_b - d_r).abs().mean().item())
                    bond_maes.append(bond_mae_i)

            # Bondi vdW steric clash rate (matching CoFoldingLoss 0.82 threshold) + PB 0.75 count.
            r_vdw = (b_true.atom_feats[i, am, 45] * 2.0).clamp(min=0.5, max=3.5)
            d_p_v = d_p[0, am][:, am]
            d_t_v = d_t[0, am][:, am]
            n_v = int(r_vdw.shape[0])
            triu = torch.triu(torch.ones((n_v, n_v), device=device, dtype=torch.bool), diagonal=1)
            lig_v = (
                b_true.is_ligand_atom[i, am]
                if b_true.is_ligand_atom is not None
                else torch.zeros(n_v, device=device, dtype=torch.bool)
            )
            involves_lig = lig_v.unsqueeze(1) | lig_v.unsqueeze(0)
            nb_pairs = triu & involves_lig & (d_t_v >= 2.2)
            min_allow = 0.82 * (r_vdw.unsqueeze(1) + r_vdw.unsqueeze(0))
            if bool(nb_pairs.any().item()):
                c_rate = float(
                    (d_p_v[nb_pairs] < min_allow[nb_pairs]).to(torch.float32).mean().item()
                )
            else:
                c_rate = 0.0
            clash_rates.append(c_rate)

            pl_pairs = triu & (lig_v.unsqueeze(1) != lig_v.unsqueeze(0))
            min_pb = 0.75 * (r_vdw.unsqueeze(1) + r_vdw.unsqueeze(0))
            pl_cnt = (
                int((d_p_v[pl_pairs] < min_pb[pl_pairs]).sum().item())
                if bool(pl_pairs.any().item())
                else 0
            )
            pl_clash_counts.append(pl_cnt)

            # Signed tetrahedral chiral volume retention.
            chi_ok_i = 0
            chi_n_i = 0
            if (
                b_true.chiral_quads is not None
                and b_true.chiral_mask is not None
                and b_true.chiral_vol_true is not None
            ):
                cm = b_true.chiral_mask[i]
                if bool(cm.any().item()):
                    vp = compute_signed_tetrahedral_volume(
                        pred[i : i + 1], b_true.chiral_quads[i : i + 1]
                    )[0, cm]
                    vt = b_true.chiral_vol_true[i, cm]
                    valid_c = vt.abs() > 1e-4
                    if bool(valid_c.any().item()):
                        vp_v = vp[valid_c]
                        vt_v = vt[valid_c]
                        same_sign = (vp_v * vt_v) > 0.0
                        chi_n_i = int(valid_c.sum().item())
                        chi_ok_i = int(same_sign.sum().item())
                        chiral_total += chi_n_i
                        chiral_preserved += chi_ok_i
                        chiral_vol_errs.extend((vp_v - vt_v).abs().detach().cpu().tolist())

            plddt_atom = conf.plddt[i, am]
            plddt_m = float(plddt_atom.mean().item())
            lig_p = float(conf.ligand_plddt[i].item())
            iptm_v = float(conf.iptm[i].item())
            ptm_v = float(conf.ptm[i].item())
            rank_v = float(conf.ranking_score[i].item())
            plddt_means.append(plddt_m)
            lig_plddts.append(lig_p)
            iptms.append(iptm_v)
            ptms.append(ptm_v)
            rankings.append(rank_v)
            if conf.predicted_pkd is not None:
                pred_pkds.append(float(conf.predicted_pkd[i].item()))
                true_pkds.append(rec.pkd_true)

            if include_per_complex:
                per_complex_rows.append(
                    {
                        "complex_id": rec.complex_id,
                        "target": rec.target_label,
                        "pdb_id": rec.pdb_id.upper(),
                        "kabsch_ligand_rmsd_A": round(k_rmsd, 4),
                        "unaligned_ligand_rmsd_A": round(u_rmsd, 4),
                        "smooth_lddt_complex": round(c_lddt, 4),
                        "smooth_lddt_ligand_interface": round(i_lddt, 4),
                        "bond_length_mae_A": _safe_float(bond_mae_i, 4),
                        "steric_clash_pair_rate": round(c_rate, 5),
                        "protein_ligand_clash_count": pl_cnt,
                        "chiral_preserved": chi_ok_i,
                        "chiral_total": chi_n_i,
                        "plddt_mean": round(plddt_m, 2),
                        "ligand_plddt": round(lig_p, 2),
                        "iptm": round(iptm_v, 4),
                        "ptm": round(ptm_v, 4),
                        "ranking_score": round(rank_v, 4),
                    }
                )

            if run_pose_audit and (audit_limit is None or len(audit_inputs) < audit_limit):
                coords_np = pred[i].detach().cpu().numpy().astype(np.float32)
                plddt_np = conf.plddt[i].detach().cpu().numpy().astype(np.float32)
                mol_3d, poc_pdb_txt = _build_cofolded_mol_and_pocket_pdb(rec, coords_np, plddt_np)
                audit_inputs.append((rec.complex_id, mol_3d, poc_pdb_txt))

    _sync_device(device)
    eval_sec = time.perf_counter() - t0

    n_eval = max(len(kabsch_rmsds), 1)
    result: dict[str, Any] = {
        "n_complexes": len(kabsch_rmsds),
        "eval_wall_time_s": round(eval_sec, 2),
        "kabsch_ligand_rmsd_mean_A": round(float(np.mean(kabsch_rmsds)), 4),
        "kabsch_ligand_rmsd_median_A": round(float(np.median(kabsch_rmsds)), 4),
        "unaligned_ligand_rmsd_mean_A": round(float(np.mean(unaligned_rmsds)), 4),
        "unaligned_ligand_rmsd_median_A": round(float(np.median(unaligned_rmsds)), 4),
        "kabsch_rmsd_lt_2A_rate": round(sum(r < 2.0 for r in kabsch_rmsds) / n_eval, 4),
        "kabsch_rmsd_lt_4A_rate": round(sum(r < 4.0 for r in kabsch_rmsds) / n_eval, 4),
        "smooth_lddt_complex_mean": round(float(np.mean(complex_lddts)), 4),
        "smooth_lddt_ligand_interface_mean": round(float(np.mean(interface_lddts)), 4),
        "bond_length_mae_A": round(float(np.mean(bond_maes)), 4) if bond_maes else None,
        "steric_clash_pair_rate": round(float(np.mean(clash_rates)), 5),
        "protein_ligand_clash_count_mean": round(float(np.mean(pl_clash_counts)), 2),
        "chiral_volume_sign_retention": (
            round(chiral_preserved / chiral_total, 4) if chiral_total > 0 else None
        ),
        "chiral_volume_mae_A3": (
            round(float(np.mean(chiral_vol_errs)), 4) if chiral_vol_errs else None
        ),
        "chiral_centers_preserved": chiral_preserved,
        "chiral_centers_total": chiral_total,
        "confidence": {
            "plddt_mean": round(float(np.mean(plddt_means)), 2),
            "ligand_plddt_mean": round(float(np.mean(lig_plddts)), 2),
            "iptm_mean": round(float(np.mean(iptms)), 4),
            "ptm_mean": round(float(np.mean(ptms)), 4),
            "ranking_score_mean": round(float(np.mean(rankings)), 4),
            "spearman_ligand_plddt_vs_kabsch_rmsd": _safe_spearman(lig_plddts, kabsch_rmsds),
            "spearman_ligand_plddt_vs_unaligned_rmsd": _safe_spearman(lig_plddts, unaligned_rmsds),
            "spearman_iptm_vs_kabsch_rmsd": _safe_spearman(iptms, kabsch_rmsds),
            "spearman_iptm_vs_unaligned_rmsd": _safe_spearman(iptms, unaligned_rmsds),
            "spearman_ranking_vs_interface_lddt": _safe_spearman(rankings, interface_lddts),
            "affinity_pkd_pearson": _safe_pearson(pred_pkds, true_pkds),
            "affinity_pkd_spearman": _safe_spearman(pred_pkds, true_pkds),
        },
    }
    if run_pose_audit and audit_inputs:
        result["pose_reality_audit"] = _audit_pose_set(
            audit_inputs, property_profile=property_profile
        )
    if include_per_complex:
        result["per_complex"] = per_complex_rows
    return result



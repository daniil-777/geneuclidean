def validate_all_5_folding_backends_on_drd2(
    drd2_record: RealComplexRecord,
    checkpoint_path: Path,
    device: torch.device,
) -> dict[str, Any]:
    """Validate all 5 registered folding backends emit schema-valid specs on human DRD2 (6CM4)."""
    print(
        "\n[Exporters] Validating all 5 FOLDING_BACKEND_REGISTRY backends on human DRD2...",
        flush=True,
    )
    drd2_seq = drd2_record.protein_sequence
    drd2_smiles = drd2_record.canonical_smiles
    drd2_pdb = drd2_record.pocket_pdb_path
    registered = list_folding_backends()

    expected_backends = ("nanofold3", "boltz2", "protenix", "alphafold3", "esmfold_api")
    missing = [b for b in expected_backends if b not in registered]
    if missing:
        raise RuntimeError(f"Missing expected backends in FOLDING_BACKEND_REGISTRY: {missing}")

    cofold_job = FoldingJobSpec(
        name="human_drd2_6cm4_risperidone",
        protein_chains=(("A", drd2_seq),),
        ligand_smiles=(("B", drd2_smiles),),
        pocket_pdb=drd2_pdb,
        pocket_contact_residues=(("A", 114), ("A", 193), ("A", 389)),
        seeds=(42,),
        num_samples=1,
        predict_affinity=True,
    )
    protein_only_job = FoldingJobSpec(
        name="human_drd2_6cm4_pocket_seq",
        protein_chains=(("A", drd2_seq),),
        seeds=(42,),
        num_samples=1,
    )

    checks: dict[str, Any] = {}
    with tempfile.TemporaryDirectory(prefix="nf3_drd2_exporters_") as tmpdir:
        tmp = Path(tmpdir)

        # 1. NanoFold3 live end-to-end execution via FOLDING_BACKEND_REGISTRY + saved best.pt
        nf_res = run_folding_backend(
            "nanofold3",
            cofold_job,
            output_dir=tmp / "nanofold3",
            run_audit=True,
            property_profile="cns_mpo_v2",
            checkpoint_path=checkpoint_path,
            device=str(device),
            num_steps=16,
        )
        pdb_lines = (nf_res.pdb_text or "").splitlines()
        atom_lines = [ln for ln in pdb_lines if ln.startswith(("ATOM  ", "HETATM"))]
        max_col = max((len(ln) for ln in atom_lines), default=0)
        nf_valid = bool(
            nf_res.backend == "nanofold3"
            and nf_res.structure_path is not None
            and nf_res.structure_path.is_file()
            and len(atom_lines) > 0
            and max_col <= 80
            and math.isfinite(nf_res.plddt_mean)
            and math.isfinite(nf_res.iptm)
            and nf_res.pose_audit is not None
            and len(nf_res.provenance_sha256) == 64
        )
        checks["nanofold3"] = {
            "schema_valid": nf_valid,
            "mode": "live_checkpoint_cofold",
            "checkpoint_path": str(checkpoint_path),
            "pdb_atom_lines": len(atom_lines),
            "pdb_max_line_cols": max_col,
            "plddt_mean": _safe_float(nf_res.plddt_mean, 2),
            "ligand_plddt": _safe_float(nf_res.ligand_plddt, 2),
            "iptm": _safe_float(nf_res.iptm, 4),
            "ptm": _safe_float(nf_res.ptm, 4),
            "runtime_sec": round(nf_res.runtime_sec, 4),
            "pose_audit_reality_score": (
                round(float(nf_res.pose_audit.reality_score), 4)
                if nf_res.pose_audit is not None
                else None
            ),
            "provenance_sha256": nf_res.provenance_sha256,
        }

        # 2. Boltz-2 YAML v1 exporter + strict yaml.safe_load round-trip
        b2_res = run_folding_backend(
            "boltz2",
            cofold_job,
            output_dir=tmp / "boltz2",
            mode="export_only",
        )
        b2_yaml_text = str(b2_res.metadata.get("input_yaml", ""))
        b2_parsed = yaml.safe_load(b2_yaml_text)
        b2_valid = bool(
            isinstance(b2_parsed, dict)
            and b2_parsed.get("version") == 1
            and len(b2_parsed.get("sequences", [])) == 2
            and b2_parsed["sequences"][0]["protein"]["sequence"] == drd2_seq
            and b2_parsed["sequences"][1]["ligand"]["smiles"] == drd2_smiles
            and b2_parsed.get("properties") == [{"affinity": {"binder": "B"}}]
            and len(b2_parsed.get("constraints", [])) == 1
        )
        checks["boltz2"] = {
            "schema_valid": b2_valid,
            "mode": "export_only",
            "format": "yaml_v1",
            "yaml_bytes": len(b2_yaml_text.encode("utf-8")),
            "version": b2_parsed.get("version") if isinstance(b2_parsed, dict) else None,
            "n_sequences": len(b2_parsed.get("sequences", []))
            if isinstance(b2_parsed, dict)
            else 0,
            "has_affinity_property": bool(
                isinstance(b2_parsed, dict) and b2_parsed.get("properties")
            ),
            "provenance_sha256": b2_res.provenance_sha256,
        }

        # 3. Protenix JSON exporter + schema verification
        px_res = run_folding_backend(
            "protenix",
            cofold_job,
            output_dir=tmp / "protenix",
            mode="export_only",
        )
        px_json = px_res.metadata.get("input_json")
        px_entry = px_json[0] if isinstance(px_json, list) and px_json else {}
        px_valid = bool(
            isinstance(px_json, list)
            and len(px_json) == 1
            and px_entry.get("name") == cofold_job.name
            and len(px_entry.get("sequences", [])) == 2
            and px_entry["sequences"][0]["proteinChain"]["sequence"] == drd2_seq
            and px_entry["sequences"][1]["ligand"]["ligand"] == drd2_smiles
        )
        checks["protenix"] = {
            "schema_valid": px_valid,
            "mode": "export_only",
            "format": "protenix_json_array",
            "n_jobs": len(px_json) if isinstance(px_json, list) else 0,
            "n_entities": len(px_entry.get("sequences", [])),
            "provenance_sha256": px_res.provenance_sha256,
        }

        # 4. AlphaFold 3 JSON dialect v2 / v3 / v4 exporter verification
        af3_versions_ok: dict[str, bool] = {}
        af3_prov = ""
        for ver in (2, 3, 4):
            af3_res = run_folding_backend(
                "alphafold3",
                cofold_job,
                output_dir=tmp / f"af3_v{ver}",
                mode="export_only",
                dialect_version=ver,
            )
            doc = af3_res.metadata.get("input_json", {})
            ok_v = bool(
                isinstance(doc, dict)
                and doc.get("dialect") == "alphafold3"
                and doc.get("version") == ver
                and doc.get("modelSeeds") == [42]
                and len(doc.get("sequences", [])) == 2
                and doc["sequences"][0]["protein"]["sequence"] == drd2_seq
                and doc["sequences"][1]["ligand"]["smiles"] == drd2_smiles
            )
            af3_versions_ok[f"v{ver}"] = ok_v
            if ver == 2:
                af3_prov = af3_res.provenance_sha256
        checks["alphafold3"] = {
            "schema_valid": all(af3_versions_ok.values()),
            "mode": "export_only",
            "format": "alphafold3_json",
            "dialects_validated": af3_versions_ok,
            "provenance_sha256": af3_prov,
        }

        # 5. ESMFold API single-sequence job validation + offline-safety & ligand-rejection guards
        validated_prot_spec = protein_only_job.validated(allow_ambiguous_aa=False)
        offline_blocked = False
        try:
            run_folding_backend("esmfold_api", validated_prot_spec, allow_network=False)
        except NetworkDisabledError:
            offline_blocked = True

        ligand_rejected = False
        try:
            run_folding_backend("esmfold_api", cofold_job, allow_network=False)
        except ValueError:
            ligand_rejected = True

        esm_valid = bool(
            len(validated_prot_spec.protein_chains) == 1
            and len(validated_prot_spec.protein_chains[0][1]) <= 400
            and offline_blocked
            and ligand_rejected
        )
        checks["esmfold_api"] = {
            "schema_valid": esm_valid,
            "mode": "offline_spec_and_safety_gate",
            "sequence_length_aa": len(validated_prot_spec.protein_chains[0][1]),
            "within_400aa_api_limit": len(validated_prot_spec.protein_chains[0][1]) <= 400,
            "offline_network_disabled_guard_passed": offline_blocked,
            "ligand_rejection_guard_passed": ligand_rejected,
        }

    all_passed = all(bool(v["schema_valid"]) for v in checks.values())
    for bname, info in checks.items():
        print(f"  backend={bname:12s} | schema_valid={info['schema_valid']}", flush=True)

    return {
        "target_complex": drd2_record.complex_id,
        "pdb_id": drd2_record.pdb_id.upper(),
        "protein_sequence_length_aa": len(drd2_seq),
        "ligand_smiles": drd2_smiles,
        "registered_backends": registered,
        "registry_size": len(FOLDING_BACKEND_REGISTRY.names()),
        "all_5_backends_valid": all_passed,
        "backends": checks,
    }



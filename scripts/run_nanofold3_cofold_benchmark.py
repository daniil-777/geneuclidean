def _sync_device(device: torch.device) -> None:
    if device.type == "mps":
        torch.mps.synchronize()
    elif device.type == "cuda":
        torch.cuda.synchronize()


def _empty_device_cache(device: torch.device) -> None:
    gc.collect()
    if device.type == "mps":
        torch.mps.synchronize()
        torch.mps.empty_cache()
    elif device.type == "cuda":
        torch.cuda.synchronize()
        torch.cuda.empty_cache()


def _memory_snapshot_mb(device: torch.device) -> dict[str, float]:
    """Return current MPS/CUDA driver memory and process peak RSS in MiB."""
    ru = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
    # macOS reports ru_maxrss in bytes; Linux reports kilobytes.
    rss_mb = float(ru) / (1024.0 * 1024.0) if sys.platform == "darwin" else float(ru) / 1024.0
    cur_mb = 0.0
    drv_mb = 0.0
    if device.type == "mps":
        cur_mb = float(torch.mps.current_allocated_memory()) / (1024.0 * 1024.0)
        drv_mb = float(torch.mps.driver_allocated_memory()) / (1024.0 * 1024.0)
    elif device.type == "cuda":
        cur_mb = float(torch.cuda.memory_allocated(device)) / (1024.0 * 1024.0)
        drv_mb = float(torch.cuda.max_memory_allocated(device)) / (1024.0 * 1024.0)
    return {
        "device_current_mb": round(cur_mb, 2),
        "device_driver_mb": round(drv_mb, 2),
        "process_peak_rss_mb": round(rss_mb, 2),
    }


def _file_sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def _safe_float(val: float | None, digits: int = 4) -> float | None:
    if val is None or not math.isfinite(float(val)):
        return None
    return round(float(val), digits)


def _safe_spearman(x: Sequence[float], y: Sequence[float]) -> dict[str, float | int | None]:
    pairs = [
        (float(a), float(b))
        for a, b in zip(x, y, strict=True)
        if math.isfinite(float(a)) and math.isfinite(float(b))
    ]
    n = len(pairs)
    if n < 3:
        return {"rho": None, "p_value": None, "n": n}
    xs = np.array([p[0] for p in pairs], dtype=np.float64)
    ys = np.array([p[1] for p in pairs], dtype=np.float64)
    if float(np.std(xs)) < 1e-12 or float(np.std(ys)) < 1e-12:
        return {"rho": 0.0, "p_value": 1.0, "n": n}
    res = spearmanr(xs, ys)
    rho = float(res.statistic)
    pval = float(res.pvalue)
    return {
        "rho": _safe_float(rho, 4),
        "p_value": _safe_float(pval, 6),
        "n": n,
    }


def _safe_pearson(x: Sequence[float], y: Sequence[float]) -> dict[str, float | int | None]:
    pairs = [
        (float(a), float(b))
        for a, b in zip(x, y, strict=True)
        if math.isfinite(float(a)) and math.isfinite(float(b))
    ]
    n = len(pairs)
    if n < 3:
        return {"r": None, "p_value": None, "n": n}
    xs = np.array([p[0] for p in pairs], dtype=np.float64)
    ys = np.array([p[1] for p in pairs], dtype=np.float64)
    if float(np.std(xs)) < 1e-12 or float(np.std(ys)) < 1e-12:
        return {"r": 0.0, "p_value": 1.0, "n": n}
    res = pearsonr(xs, ys)
    return {
        "r": _safe_float(float(res.statistic), 4),
        "p_value": _safe_float(float(res.pvalue), 6),
        "n": n,
    }



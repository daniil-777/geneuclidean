@torch.inference_mode()
def run_mps_inference_latency_benchmark(
    drd2_record: RealComplexRecord,
    device: torch.device,
    *,
    num_steps: int = 12,
    n_warmup: int = 2,
    n_timed: int = 5,
) -> dict[str, Any]:
    """Measure exact warmed-up ms/complex on real DRD2 and L=64 / L=128 token scaling."""
    print(
        "\n[MPS Latency] Benchmarking Pairformer vs SimpleFold inference ms/complex...", flush=True
    )

    # 1. Real human DRD2 (6CM4_DRD2_8NU) exact batch
    drd2_batch = drd2_record.batch_eval_input.to(device)
    drd2_n = int(drd2_batch.coords.shape[1])
    drd2_l = int(drd2_batch.token_mask.shape[1])

    # 2. Construct L=64 (N=192) and L=128 (N=320) real-pocket-shaped scaling batches
    def _make_scaling_batch(n_atoms: int, n_tokens: int, n_lig: int) -> ComplexBatch:
        gen = torch.Generator(device="cpu").manual_seed(42 + n_tokens)
        n_poc = n_atoms - n_lig
        n_res = n_tokens - n_lig
        coords = torch.randn((1, n_atoms, 3), generator=gen, dtype=torch.float32) * 4.0
        feats = torch.zeros((1, n_atoms, 52), dtype=torch.float32)
        feats[:, :n_poc, 0] = 1.0
        feats[:, :n_poc, 10] = 1.0
        feats[:, :n_poc:4, 42] = 1.0
        feats[:, n_poc:, 0] = 1.0
        feats[:, n_poc:, 30] = 1.0
        feats[:, :, 45] = 0.85
        feats[:, :, 46] = torch.randn((1, n_atoms), generator=gen) * 0.15

        poc_a2t = torch.linspace(0, n_res - 1, steps=n_poc).long().clamp(0, n_res - 1)
        lig_a2t = torch.arange(n_res, n_tokens, dtype=torch.long)
        a2t = torch.cat((poc_a2t, lig_a2t), dim=0).unsqueeze(0)
        chain_id = torch.cat(
            (torch.zeros(n_res, dtype=torch.long), torch.ones(n_lig, dtype=torch.long))
        ).unsqueeze(0)
        tok_type = torch.cat(
            (torch.arange(n_res, dtype=torch.long) % 20, torch.full((n_lig,), 21, dtype=torch.long))
        ).unsqueeze(0)
        res_idx = torch.cat(
            (torch.arange(n_res, dtype=torch.long), torch.arange(n_lig, dtype=torch.long))
        ).unsqueeze(0)
        is_lig = torch.cat(
            (torch.zeros(n_poc, dtype=torch.bool), torch.ones(n_lig, dtype=torch.bool))
        ).unsqueeze(0)
        is_bb = feats[:, :, 42] > 0.5
        rep_idx = torch.cat(
            (
                torch.linspace(0, n_poc - 1, steps=n_res).long(),
                torch.arange(n_poc, n_atoms, dtype=torch.long),
            )
        ).unsqueeze(0)
        return ComplexBatch(
            coords=coords,
            atom_feats=feats,
            atom_to_token=a2t,
            atom_mask=torch.ones((1, n_atoms), dtype=torch.bool),
            token_mask=torch.ones((1, n_tokens), dtype=torch.bool),
            chain_id=chain_id,
            token_type=tok_type,
            res_index=res_idx,
            flex_mask=~is_bb,
            is_ligand_atom=is_lig,
            is_backbone_atom=is_bb,
            token_rep_atom_idx=rep_idx,
            covalent_adj=torch.zeros((1, n_atoms, n_atoms, 6), dtype=torch.float32),
        ).to(device)

    workloads: dict[str, tuple[ComplexBatch, int, int]] = {
        "real_drd2_6cm4": (drd2_batch, drd2_n, drd2_l),
        "pocket_L64_N192": (_make_scaling_batch(192, 64, 24), 192, 64),
        "pocket_L128_N320": (_make_scaling_batch(320, 128, 32), 320, 128),
    }

    results: dict[str, Any] = {
        "num_sampling_steps": num_steps,
        "num_warmup_runs": n_warmup,
        "num_timed_runs": n_timed,
        "mps_fallback_env": os.environ.get("PYTORCH_ENABLE_MPS_FALLBACK", "unset"),
        "workloads": {},
    }

    for wl_name, (batch, n_a, l_t) in workloads.items():
        wl_out: dict[str, Any] = {"n_atoms": n_a, "n_tokens": l_t, "models": {}}
        for spec in MODEL_MATRIX:
            m = build_nanofold3(
                "nano",
                trunk_mode=spec.trunk_mode,
                diffusion_mode=spec.diffusion_mode,
                device=device,
            )
            m.eval()
            for w in range(n_warmup):
                _ = m.sample(
                    batch,
                    num_steps=num_steps,
                    num_samples=1,
                    flex_mode="flexible_pocket_and_ligand",
                    seed=10 + w,
                )
            _sync_device(device)

            # Time full end-to-end sample (trunk + diffusion + confidence) and trunk-only.
            full_times_ms: list[float] = []
            for r in range(n_timed):
                _sync_device(device)
                t0 = time.perf_counter()
                _ = m.sample(
                    batch,
                    num_steps=num_steps,
                    num_samples=1,
                    flex_mode="flexible_pocket_and_ligand",
                    seed=100 + r,
                )
                _sync_device(device)
                full_times_ms.append((time.perf_counter() - t0) * 1000.0)

            trunk_times_ms: list[float] = []
            eff_flex = m._resolve_batch_flex_mask(batch, "flexible_pocket_and_ligand")
            for _ in range(n_timed):
                _sync_device(device)
                t0 = time.perf_counter()
                _ = m.forward_trunk(batch, flex_mask=eff_flex)
                _sync_device(device)
                trunk_times_ms.append((time.perf_counter() - t0) * 1000.0)

            mem = _memory_snapshot_mb(device)
            wl_out["models"][spec.run_name] = {
                "trunk_mode": spec.trunk_mode,
                "diffusion_mode": spec.diffusion_mode,
                "num_parameters": m.num_parameters,
                "sample_median_ms": round(statistics.median(full_times_ms), 2),
                "sample_mean_ms": round(statistics.mean(full_times_ms), 2),
                "sample_min_ms": round(min(full_times_ms), 2),
                "sample_max_ms": round(max(full_times_ms), 2),
                "trunk_only_median_ms": round(statistics.median(trunk_times_ms), 2),
                "device_driver_mb": mem["device_driver_mb"],
            }
            print(
                f"  {wl_name:16s} | {spec.run_name:24s} | "
                f"sample={statistics.median(full_times_ms):6.1f} ms | "
                f"trunk={statistics.median(trunk_times_ms):5.1f} ms",
                flush=True,
            )
            del m
            _empty_device_cache(device)

        # Pairformer vs SimpleFold speedup ratios on matching diffusion schedules.
        pf_edm = wl_out["models"]["pairformer_edm"]["sample_median_ms"]
        sf_edm = wl_out["models"]["simplefold_edm"]["sample_median_ms"]
        pf_fm = wl_out["models"]["pairformer_flow_matching"]["sample_median_ms"]
        sf_fm = wl_out["models"]["simplefold_flow_matching"]["sample_median_ms"]
        pf_tr = wl_out["models"]["pairformer_edm"]["trunk_only_median_ms"]
        sf_tr = wl_out["models"]["simplefold_edm"]["trunk_only_median_ms"]
        wl_out["simplefold_speedup_vs_pairformer"] = {
            "trunk_only_speedup_x": round(pf_tr / max(sf_tr, 1e-6), 2),
            "edm_sample_speedup_x": round(pf_edm / max(sf_edm, 1e-6), 2),
            "flow_matching_sample_speedup_x": round(pf_fm / max(sf_fm, 1e-6), 2),
        }
        results["workloads"][wl_name] = wl_out

    return results



def train_and_evaluate_variant(
    spec: ModelSpec,
    train_records: Sequence[RealComplexRecord],
    val_records: Sequence[RealComplexRecord],
    test_records: Sequence[RealComplexRecord],
    cns_records: Sequence[RealComplexRecord],
    device: torch.device,
    *,
    epochs: int,
    batch_size: int,
    lr: float,
    max_n: int,
    max_l: int,
    eval_steps: int,
    seed: int,
    audit_test_limit: int,
) -> tuple[dict[str, Any], dict[str, Tensor], float]:
    """Train one NanoFold3 preset='nano' variant on real complexes and evaluate before/after."""
    print(
        f"\n[Run] {spec.run_name} (trunk={spec.trunk_mode}, schedule={spec.diffusion_mode})",
        flush=True,
    )
    seed_everything(seed)
    model = build_nanofold3(
        "nano",
        trunk_mode=spec.trunk_mode,
        diffusion_mode=spec.diffusion_mode,
        enable_affinity_head=True,
        device=device,
    )
    num_params = model.num_parameters

    # Verify strict float32 parameters & buffers (Apple MPS native invariant).
    non_f32 = [name for name, p in model.named_parameters() if p.dtype != torch.float32] + [
        name
        for name, b in model.named_buffers()
        if b.is_floating_point() and b.dtype != torch.float32
    ]
    if non_f32:
        raise RuntimeError(f"Non-float32 tensors in NanoFold3: {non_f32}")

    # 1. Untrained baseline evaluation (strictly zero-leakage).
    untrained_test = evaluate_model_on_records(
        model,
        test_records,
        device,
        max_n=max_n,
        max_l=max_l,
        batch_size=batch_size,
        num_steps=eval_steps,
        seed=seed,
        run_pose_audit=True,
        audit_limit=audit_test_limit,
        property_profile="oral_ro5",
    )
    untrained_cns = evaluate_model_on_records(
        model,
        cns_records,
        device,
        max_n=max_n,
        max_l=max_l,
        batch_size=min(batch_size, len(cns_records)),
        num_steps=eval_steps,
        seed=seed,
        run_pose_audit=True,
        audit_limit=None,
        property_profile="cns_mpo_v2",
        include_per_complex=True,
    )
    print(
        f"  [Untrained] test kabsch={untrained_test['kabsch_ligand_rmsd_mean_A']:.2f} A "
        f"| lddt_if={untrained_test['smooth_lddt_ligand_interface_mean']:.3f} "
        f"| bond_mae={untrained_test['bond_length_mae_A']:.2f} A "
        f"| CNS kabsch={untrained_cns['kabsch_ligand_rmsd_mean_A']:.2f} A",
        flush=True,
    )

    # 2. Training loop with AdamW, linear warmup + cosine LR, grad clip, and EMA weights.
    optimizer = torch.optim.AdamW(model.parameters(), lr=lr, weight_decay=1e-4)
    n_train = len(train_records)
    steps_per_epoch = max(1, math.ceil(n_train / batch_size))
    total_steps = epochs * steps_per_epoch
    warmup_steps = max(1, min(2 * steps_per_epoch, total_steps // 4))

    def _lr_lambda(step: int) -> float:
        if step < warmup_steps:
            return float(step + 1) / float(warmup_steps)
        prog = float(step - warmup_steps) / float(max(total_steps - warmup_steps, 1))
        return 0.05 + 0.95 * 0.5 * (1.0 + math.cos(math.pi * min(max(prog, 0.0), 1.0)))

    scheduler = torch.optim.lr_scheduler.LambdaLR(optimizer, lr_lambda=_lr_lambda)
    ema = _ModelEMA(model, decay=0.96)

    rng = np.random.default_rng(seed)
    epoch_history: list[dict[str, Any]] = []
    best_val_score = float("inf")
    best_val_epoch = 0
    best_state_cpu: dict[str, Tensor] = {
        k: v.detach().cpu().clone() for k, v in model.state_dict().items()
    }
    peak_device_driver_mb = 0.0
    peak_rss_mb = 0.0

    # Pre-collate fixed validation batches for fast loss monitoring.
    val_batches = [
        collate_complex_batches(
            val_records[s : s + batch_size], use_eval_input=False, max_n=max_n, max_l=max_l
        ).to(device)
        for s in range(0, len(val_records), batch_size)
    ]

    train_t0 = time.perf_counter()
    global_step = 0
    for ep in range(1, epochs + 1):
        ep_t0 = time.perf_counter()
        model.train()
        perm = rng.permutation(n_train)
        sums: dict[str, float] = {
            "total": 0.0,
            "coord": 0.0,
            "smooth_lddt": 0.0,
            "bond": 0.0,
            "chiral": 0.0,
            "clash": 0.0,
            "tether": 0.0,
            "confidence": 0.0,
        }
        n_batches_ep = 0

        for s in range(0, n_train, batch_size):
            idx_chunk = perm[s : s + batch_size]
            if len(idx_chunk) == 0:
                continue
            chunk = [train_records[int(j)] for j in idx_chunk]
            cb = collate_complex_batches(chunk, use_eval_input=False, max_n=max_n, max_l=max_l).to(
                device
            )

            optimizer.zero_grad(set_to_none=True)
            out = model.forward_train(
                cb,
                flex_mode="flexible_pocket_and_ligand",
                conf_loss_weight=0.5,
                seed=seed * 10000 + ep * 1000 + n_batches_ep,
            )
            out.loss.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)
            optimizer.step()
            scheduler.step()
            ema.update(model)

            cl = out.cofolding_loss
            sums["total"] += float(out.loss.detach().item())
            sums["coord"] += float(cl.coord.detach().item())
            sums["smooth_lddt"] += float(cl.smooth_lddt.detach().item())
            sums["bond"] += float(cl.bond.detach().item())
            sums["chiral"] += float(cl.chiral.detach().item())
            sums["clash"] += float(cl.clash.detach().item())
            sums["tether"] += float(cl.tether.detach().item())
            sums["confidence"] += float(out.confidence_loss.detach().item())
            n_batches_ep += 1
            global_step += 1

        _sync_device(device)
        mem = _memory_snapshot_mb(device)
        peak_device_driver_mb = max(peak_device_driver_mb, mem["device_driver_mb"])
        peak_rss_mb = max(peak_rss_mb, mem["process_peak_rss_mb"])

        ep_entry: dict[str, Any] = {
            "epoch": ep,
            "lr": round(float(optimizer.param_groups[0]["lr"]), 6),
            "epoch_wall_time_s": round(time.perf_counter() - ep_t0, 2),
            "train_loss": {k: round(v / max(n_batches_ep, 1), 4) for k, v in sums.items()},
        }

        # Monitor validation CoFoldingLoss + sampled RMSD/LDDT on checkpoints & final epoch.
        if ep in (1, 4, 8, 12, epochs) or ep % 4 == 0:
            backup = ema.apply_to(model)
            model.eval()
            val_loss_sum = 0.0
            val_conf_sum = 0.0
            with torch.inference_mode():
                for vb_i, vb in enumerate(val_batches):
                    vout = model.forward_train(
                        vb,
                        flex_mode="flexible_pocket_and_ligand",
                        conf_loss_weight=0.5,
                        seed=seed + 777 + vb_i,
                    )
                    val_loss_sum += float(vout.loss.item())
                    val_conf_sum += float(vout.confidence_loss.item())
            val_metrics = evaluate_model_on_records(
                model,
                val_records,
                device,
                max_n=max_n,
                max_l=max_l,
                batch_size=batch_size,
                num_steps=eval_steps,
                seed=seed + 100,
                run_pose_audit=False,
            )
            # Selection criterion: minimize validation Kabsch RMSD + 2.0 * (1 - interface_lddt)
            val_k = float(val_metrics["kabsch_ligand_rmsd_mean_A"])
            val_il = float(val_metrics["smooth_lddt_ligand_interface_mean"])
            sel_score = val_k + 2.0 * (1.0 - val_il)
            if sel_score < best_val_score:
                best_val_score = sel_score
                best_val_epoch = ep
                best_state_cpu = {
                    k: v.detach().cpu().clone() for k, v in model.state_dict().items()
                }
            model.load_state_dict(backup, strict=True)

            ep_entry["val_loss_total"] = round(val_loss_sum / max(len(val_batches), 1), 4)
            ep_entry["val_loss_conf"] = round(val_conf_sum / max(len(val_batches), 1), 4)

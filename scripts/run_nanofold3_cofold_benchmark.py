class _ModelEMA:
    """Float32 Exponential Moving Average shadow weights for stable diffusion sampling."""

    def __init__(self, model: NanoFold3, decay: float = 0.96) -> None:
        self.decay = float(decay)
        self.step = 0
        self.shadow: dict[str, Tensor] = {
            k: v.detach().clone() for k, v in model.state_dict().items()
        }

    @torch.no_grad()
    def update(self, model: NanoFold3) -> None:
        self.step += 1
        d = min(self.decay, (1.0 + self.step) / (10.0 + self.step))
        for k, v in model.state_dict().items():
            if v.is_floating_point():
                self.shadow[k].mul_(d).add_(v.detach(), alpha=1.0 - d)
            else:
                self.shadow[k].copy_(v.detach())

    def apply_to(self, model: NanoFold3) -> dict[str, Tensor]:
        backup = {k: v.detach().clone() for k, v in model.state_dict().items()}
        model.load_state_dict(self.shadow, strict=True)
        return backup



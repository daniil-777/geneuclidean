#!/usr/bin/env python3
"""Real Apple M3 Pro MPS Training & Co-Folding Benchmark for GenEuclidean NanoFold3.

Executes a strictly zero-leakage, end-to-end training and evaluation benchmark of
:class:`geneuclidean.folding.nanofold3.NanoFold3` (``preset="nano"``) on real
protein-ligand crystal/cryo-EM structures from local ``data/raw/pbpp2020``,
``data/raw/LP_PDBBind.csv``, ``data/cns_neuro.nosync/structures/clean_pockets/``, and
``data/cns_neuro.nosync/v4_expansion/structures/clean_pockets/`` under strict
``PYTORCH_ENABLE_MPS_FALLBACK=0``:

1. **Zero-Leakage Real Dataset Construction:**
   - Uses LP-PDBBind protein-clustered train/val/test splits and additionally filters out
     every PDB ID, exact protein sequence, canonical ligand SMILES, and target-family
     overlap across ``train``, ``val``, ``test``, and the human CNS evaluation panel
     (``DRD1``, ``DRD2``, ``CHRM4``, ``MAOB``).
   - Centers every complex strictly on the pocket PDB heavy-atom centroid (matching
     ``NanoFold3.cofold(pocket_pdb, ligand_smiles, pocket_center=None)``) and computes
     ligand 52-D features, covalent adjacency, and ideal 1-2/1-3 bond references from
     fresh RDKit ETKDGv3 conformers — ensuring zero 3D crystal coordinate leakage into
     input features or evaluation initializations.
2. **4-Way Apple M3 Pro MPS Training Matrix (2 Trunks x 2 Schedules):**
   - Trains ``pairformer`` vs. ``simplefold`` trunks crossed with ``edm`` vs.
     ``flow_matching`` diffusion schedules using unmodified ``NanoFold3.forward_train``
     (6-term ``CoFoldingLoss`` + AF3 Alg. 31 ``ConfidenceLoss`` + EMA weights).
   - Saves the best validation checkpoint to
     ``runs_local.nosync/nanofold3_pocket_nano/best.pt`` and verifies clean
     ``NanoFold3.from_pretrained`` round-trip loading.
3. **Honest Untrained vs. Trained Evaluation (Held-Out Test & Human CNS Pockets):**
   - Measures reflection-safe ``SO(3)`` Kabsch-aligned ligand RMSD, unaligned pocket-frame
     ligand RMSD, complex & ligand-interface Smooth LDDT, Bondi vdW steric clash rates,
     1-2 covalent bond-length MAE, signed tetrahedral chiral volume retention, ``pLDDT`` /
     ``ipTM`` calibration (Spearman ``rho`` vs. actual RMSD), and 7-axis
     :class:`PoseRealityAuditor` physical pass rates alongside crystal baselines.
4. **MPS Inference Latency & All 5 ``FOLDING_BACKEND_REGISTRY`` Exporters:**
   - Profiles warmed-up ``ms/complex`` under ``PYTORCH_ENABLE_MPS_FALLBACK=0`` on real
     human ``DRD2`` (``6CM4``) plus ``L=64`` / ``L=128`` scaling.
   - Validates all 5 backends (``nanofold3``, ``boltz2``, ``protenix``, ``alphafold3``,
     ``esmfold_api``) on real human ``DRD2`` (``6CM4_DRD2_8NU``).

Outputs a SHA-256-verified JSON report with explicit non-regulatory *in silico*
disclaimers to ``results/tables/nanofold3_cofold_v53_benchmark.json``.
"""

